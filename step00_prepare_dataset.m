function outputs = step00_prepare_dataset(configInput)
%STEP00_PREPARE_DATASET Audit descriptors, deduplicate identities, and freeze dataset partitions.
%   With no input, use the formal profile from functions/pso_mdl_config.m.
%   CONFIGINPUT can also be a profile name or a configuration structure.
%   Results are written only under the configured output directory.
root = fileparts(mfilename('fullpath'));
addpath(root);
addpath(fullfile(root, 'functions'));
if nargin < 1, configInput = "formal"; end
cfg = resolve_pso_mdl_config(configInput);
paths = pso_mdl_paths(cfg);
projectRoot = root;
missingnessSummaryFiles = match_input_files(cfg.Input.MissingnessCache);
auditDir = paths.Audit;
assert_output_available(fullfile(paths.Cache, 'dataset_metadata.mat'), cfg.Output.Overwrite);
stableIdentifierColumn = cfg.Identity.CandidateIdentifierColumn;
referenceIdentifierColumn = cfg.Identity.ReferenceIdentifierColumn;
duplicateTieBreakColumns = cfg.Identity.TieBreakColumns;
missingIdentifierPolicy = cfg.Identity.MissingIdentifierPolicy;
excludeReferenceOverlap = cfg.Identity.ExcludeReferenceOverlap;
backgroundSelectionMode = cfg.Background.SelectionMode;
backgroundSizeMode = cfg.Background.SizeMode;
backgroundFixedCount = cfg.Background.FixedCount;
backgroundFraction = cfg.Background.Fraction;
backgroundMaximumCount = cfg.Background.MaximumCount;
backgroundMinimumCount = cfg.Background.MinimumCount;
minimumFormalHoldoutCount = cfg.Background.MinimumHoldoutCount;
backgroundRandomSeed = cfg.Background.RandomSeed;
matchingPropertyNames = cfg.Background.MatchingProperties;
candidateChunkRows = cfg.IO.CandidateChunkRows;
referenceChunkRows = cfg.IO.ReferenceChunkRows;
progressInterval = cfg.IO.ProgressInterval;
computeInputSHA256 = cfg.IO.ComputeInputSHA256;

% Freeze identities and partition membership before descriptor fitting.
deduplicationAuditFile = fullfile(auditDir, ...
    'candidate_deduplication_audit.tsv');
partitionTableFile = fullfile(auditDir, ...
    'candidate_partition.tsv');
backgroundTableFile = fullfile(auditDir, ...
    'background_training.tsv');
holdoutTableFile = fullfile(paths.Cache, ...
    'screening_holdout.tsv');
excludedTableFile = fullfile(auditDir, ...
    'candidate_exclusions.tsv');
propertySummaryFile = fullfile(auditDir, ...
    'background_property_summary.tsv');
missingnessOutputFile = fullfile(paths.Cache, ...
    'descriptor_missingness_dataset.tsv');
partitionMatFile = fullfile(paths.Cache, 'dataset_partition.mat');
metadataMatFile = fullfile(paths.Cache, 'dataset_metadata.mat');
overviewJsonFile = fullfile(auditDir, 'dataset_overview.json');
inputHashFile = fullfile(auditDir, 'input_sha256_audit.tsv');

startedAt = datetime('now', 'TimeZone', 'local');
fprintf('\n=== STEP 00: descriptor audit, deduplication, and partitioning ===\n');
fprintf('Started: %s\n', char(startedAt, 'yyyy-MM-dd HH:mm:ss'));
fprintf('Repository: %s\n\n', projectRoot);

if isfolder(cfg.Input.CandidateDescriptors)
    candidateDescriptorFile = cfg.Input.CandidateDescriptors;
else
    candidateDescriptorFile = resolve_input_file( ...
        cfg.Input.CandidateDescriptors, 'Candidate descriptor TXT or part directory', true);
end
referenceDescriptorFile = resolve_input_file( ...
    cfg.Input.ReferenceDescriptors, 'Reference descriptor TXT', true);
candidateManifestFile = resolve_input_file( ...
    cfg.Input.CandidateManifest, 'Candidate identity manifest', true);
referenceIdentityFile = resolve_input_file( ...
    cfg.Input.ReferenceManifest, 'Reference identity manifest', ...
    excludeReferenceOverlap);
missingnessInputFile = resolve_input_file( ...
    missingnessSummaryFiles, 'Candidate descriptor missingness cache', false);

[candidateIdentifierHeaders, candidateDescriptorHeaders, ...
    candidateHeaderAudit] = read_descriptor_header( ...
    string(candidateDescriptorFile));
[referenceIdentifierHeaders, referenceDescriptorHeaders, ...
    referenceHeaderAudit] = read_descriptor_header( ...
    string(referenceDescriptorFile));

assert(isequal(candidateIdentifierHeaders, ...
    referenceIdentifierHeaders), ...
    'Candidate and reference identifier headers disagree.');
assert(isequal(candidateDescriptorHeaders, ...
    referenceDescriptorHeaders), ...
    ['Candidate and reference descriptor names or order disagree;' ...
     ' training and ranking require the same descriptor schema.']);
descriptorCount = numel(candidateDescriptorHeaders);
referenceCount = count_text_data_rows( ...
    string(referenceDescriptorFile));
assert(referenceCount >= 2, ...
    'The relative-gap objective requires at least two references; found %d.', ...
    referenceCount);

fprintf('Detected %d descriptors and %d reference molecules.\n', ...
    descriptorCount, referenceCount);

fprintf('\n[1/5] Deduplicating candidates by %s and checking reference overlap...\n', ...
    stableIdentifierColumn);
[deduplicationAudit, deduplicationSummary] = ...
    deduplicate_candidate_manifest( ...
    string(candidateManifestFile), ...
    'IdentifierColumn', stableIdentifierColumn, ...
    'TieBreakColumns', duplicateTieBreakColumns, ...
    'MissingIdentifierPolicy', missingIdentifierPolicy, ...
    'ReferenceManifestFile', string(referenceIdentityFile), ...
    'ReferenceIdentifierColumn', referenceIdentifierColumn, ...
    'ExcludeReferenceOverlap', excludeReferenceOverlap);
candidateCount = height(deduplicationAudit);

fprintf(['Candidate rows %d; unique stable identities %d; duplicate nonrepresentatives %d;' ...
    ' missing identities excluded %d; reference overlaps excluded %d; eligible unique %d.\n'], ...
    candidateCount, ...
    deduplicationSummary.UniqueCandidateIdentifierCount, ...
    deduplicationSummary.DuplicateNonRepresentativeCount, ...
    deduplicationSummary.MissingIdentifierExcludedCount, ...
    deduplicationSummary.ReferenceOverlapExcludedCount, ...
    deduplicationSummary.EligibleUniqueCount);
writetable(deduplicationAudit, deduplicationAuditFile, ...
    'FileType', 'text', 'Delimiter', '\t');

fprintf('\n[2/5] Reading reference descriptors and auditing missingness...\n');
[referenceRaw, referenceDragonNames, ...
    readReferenceDescriptorNames, referenceReadAudit] = ...
    read_descriptor_rows( ...
    string(referenceDescriptorFile), ...
    (1:referenceCount).', referenceCount, descriptorCount, ...
    min(referenceChunkRows, referenceCount), referenceCount);
assert(isequal(readReferenceDescriptorNames, ...
    candidateDescriptorHeaders), ...
    'Reference descriptors disagree with candidate header.');

referenceDisplayNames = referenceDragonNames;
referenceGroups = repmat("Unspecified", referenceCount, 1);
if strlength(string(referenceIdentityFile)) > 0
    referenceIdentity = readtable(referenceIdentityFile, ...
        'FileType', 'text', 'Delimiter', '\t', ...
        'TextType', 'string', 'VariableNamingRule', 'preserve');
    assert(height(referenceIdentity) == referenceCount, ...
        'Reference manifest has %d rows; descriptor TXT has %d.', ...
        height(referenceIdentity), referenceCount);
    if ismember("DragonName", ...
            string(referenceIdentity.Properties.VariableNames))
        assert(isequal(string(referenceIdentity.DragonName), ...
            referenceDragonNames), ...
            'Reference manifest DragonName order disagrees with descriptor TXT.');
    end
    if ismember("DisplayName", ...
            string(referenceIdentity.Properties.VariableNames))
        referenceDisplayNames = string(referenceIdentity.DisplayName);
    end
    if ismember("ReferenceGroup", ...
            string(referenceIdentity.Properties.VariableNames))
        referenceGroups = string(referenceIdentity.ReferenceGroup);
    end
end

referenceMissingCount = sum(isnan(referenceRaw), 1);
referenceInfCount = sum(isinf(referenceRaw), 1);

fprintf('\n[3/5] Auditing candidate-library descriptor missingness...\n');
if strlength(string(missingnessInputFile)) > 0
    missingnessInput = readtable(missingnessInputFile, ...
        'FileType', 'text', 'Delimiter', '\t', ...
        'TextType', 'string', 'VariableNamingRule', 'preserve');
    requiredMissingVariables = [ ...
        "DescriptorIndex", "DescriptorName", ...
        "CandidateMissingCount", "CandidateInfCount", ...
        "CandidateFiniteCount"];
    assert(all(ismember(requiredMissingVariables, ...
        string(missingnessInput.Properties.VariableNames))), ...
        'Missingness cache lacks required fields.');
    assert(height(missingnessInput) == descriptorCount, ...
        'Missingness cache requires %d rows; found %d.', ...
        descriptorCount, height(missingnessInput));
    assert(isequal(double(missingnessInput.DescriptorIndex), ...
        (1:descriptorCount).') && ...
        isequal(string(missingnessInput.DescriptorName), ...
        candidateDescriptorHeaders(:)), ...
        'Missingness cache descriptor indices or names disagree with input header.');
    candidateMissingCount = ...
        double(missingnessInput.CandidateMissingCount).';
    candidateInfCount = ...
        double(missingnessInput.CandidateInfCount).';
    suppliedCandidateFiniteCount = ...
        double(missingnessInput.CandidateFiniteCount).';
    assert(all(candidateMissingCount >= 0 & ...
        candidateInfCount >= 0 & ...
        suppliedCandidateFiniteCount >= 0 & ...
        candidateMissingCount + candidateInfCount + ...
        suppliedCandidateFiniteCount == candidateCount), ...
        ['Missingness cache was not generated from these %d candidate rows;' ...
         ' clear the cache setting to rescan descriptors in Step 00.'], ...
        candidateCount);
    candidateMissingnessAudit = struct( ...
        'Mode', 'validated supplied summary', ...
        'InputFile', missingnessInputFile);
    fprintf('Validated and reused: %s\n', missingnessInputFile);
else
    fprintf(['No missingness cache supplied; scanning %d candidates and' ...
        ' %d descriptors.\n'], candidateCount, descriptorCount);
    [candidateMissingCount, candidateInfCount, ...
        missingDescriptorNames, candidateMissingnessAudit] = ...
        audit_descriptor_missingness( ...
        string(candidateDescriptorFile), candidateCount, ...
        descriptorCount, max(100, floor(candidateChunkRows / 2)), ...
        progressInterval);
    assert(isequal(missingDescriptorNames, ...
        candidateDescriptorHeaders), ...
        'Missingness audit names disagree with input header.');
end

descriptorIndex = (1:descriptorCount).';
descriptorName = candidateDescriptorHeaders(:);
candidateMissingCountColumn = candidateMissingCount(:);
candidateInfCountColumn = candidateInfCount(:);
referenceMissingCountColumn = referenceMissingCount(:);
referenceInfCountColumn = referenceInfCount(:);
candidateFiniteCount = candidateCount - ...
    candidateMissingCountColumn - candidateInfCountColumn;
referenceFiniteCount = referenceCount - ...
    referenceMissingCountColumn - referenceInfCountColumn;
completeAcrossAllMolecules = ...
    candidateMissingCountColumn == 0 & ...
    candidateInfCountColumn == 0 & ...
    referenceMissingCountColumn == 0 & ...
    referenceInfCountColumn == 0;
missingnessTable = table( ...
    descriptorIndex, descriptorName, ...
    referenceMissingCountColumn, ...
    referenceMissingCountColumn / referenceCount, ...
    referenceInfCountColumn, referenceFiniteCount, ...
    candidateMissingCountColumn, ...
    candidateMissingCountColumn / candidateCount, ...
    candidateInfCountColumn, candidateFiniteCount, ...
    completeAcrossAllMolecules, ...
    'VariableNames', { ...
    'DescriptorIndex', 'DescriptorName', ...
    'ReferenceMissingCount', 'ReferenceMissingRate', ...
    'ReferenceInfCount', 'ReferenceFiniteCount', ...
    'CandidateMissingCount', 'CandidateMissingRate', ...
    'CandidateInfCount', 'CandidateFiniteCount', ...
    'CompleteAcrossAllMolecules'});
writetable(missingnessTable, missingnessOutputFile, ...
    'FileType', 'text', 'Delimiter', '\t');

fprintf('\n[4/5] Constructing %s background and holdout partitions...\n', ...
    backgroundSelectionMode);
if lower(backgroundSelectionMode) == "property_matched"
    propertyDescriptorIndices = zeros( ...
        numel(matchingPropertyNames), 1);
    for propertyIndex = 1:numel(matchingPropertyNames)
        match = find(candidateDescriptorHeaders == ...
            matchingPropertyNames(propertyIndex));
        assert(isscalar(match), ...
            'Matching property %s must occur once in descriptor header; found %d.', ...
            matchingPropertyNames(propertyIndex), numel(match));
        propertyDescriptorIndices(propertyIndex) = match;
    end
    fprintf('Reading %d matching properties for all candidates...\n', ...
        numel(matchingPropertyNames));
    [candidateProperties, candidateDragonNames, ...
        readPropertyNames, candidatePropertyReadAudit] = ...
        read_descriptor_columns( ...
        string(candidateDescriptorFile), ...
        propertyDescriptorIndices, candidateCount, ...
        descriptorCount, candidateChunkRows, progressInterval);
    assert(isequal(readPropertyNames, ...
        matchingPropertyNames(:)), ...
        'Matching-property names or order disagree.');
    assert(isequal(candidateDragonNames, ...
        string(deduplicationAudit.DragonName)), ...
        ['Candidate manifest DragonName order disagrees with descriptor TXT;' ...
         ' SourceRow cannot safely locate descriptor records.']);
    targetProperties = ...
        double(referenceRaw(:, propertyDescriptorIndices));
    propertyNamesUsed = matchingPropertyNames(:);
else

    [~, candidateDragonNames, ~, candidatePropertyReadAudit] = ...
        read_descriptor_columns( ...
        string(candidateDescriptorFile), 1, candidateCount, ...
        descriptorCount, candidateChunkRows, progressInterval);
    assert(isequal(candidateDragonNames, ...
        string(deduplicationAudit.DragonName)), ...
        ['Candidate manifest DragonName order disagrees with descriptor TXT;' ...
         ' SourceRow cannot safely locate descriptor records.']);
    candidateProperties = zeros(candidateCount, 0);
    targetProperties = zeros(referenceCount, 0);
    propertyNamesUsed = strings(0, 1);
    propertyDescriptorIndices = zeros(0, 1);
    candidatePropertyReadAudit.Mode = ...
        'one-column full-row alignment audit for random background';
end

[partitionTable, backgroundTable, holdoutTable, ...
    excludedTable, partitionMetadata, propertySummary] = ...
    select_background_partition( ...
    deduplicationAudit, candidateProperties, ...
    targetProperties, referenceDragonNames, ...
    propertyNamesUsed, ...
    'SelectionMode', backgroundSelectionMode, ...
    'SizeMode', backgroundSizeMode, ...
    'FixedCount', backgroundFixedCount, ...
    'Fraction', backgroundFraction, ...
    'MaximumCount', backgroundMaximumCount, ...
    'MinimumCount', backgroundMinimumCount, ...
    'MinimumHoldoutCount', minimumFormalHoldoutCount, ...
    'RandomSeed', backgroundRandomSeed);

writetable(partitionTable, partitionTableFile, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(backgroundTable, backgroundTableFile, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(holdoutTable, holdoutTableFile, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(excludedTable, excludedTableFile, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(propertySummary, propertySummaryFile, ...
    'FileType', 'text', 'Delimiter', '\t');

fprintf('\n[5/5] Recording input versions and software environment...\n');
hashPaths = [ ...
    candidateHeaderAudit.SourceFiles(:); ...
    string(referenceDescriptorFile); ...
    string(candidateManifestFile)];
hashRoles = [ ...
    repmat("CandidateDragonDescriptors", numel(candidateHeaderAudit.SourceFiles), 1); ...
    "ReferenceDragonDescriptors"; ...
    "CandidateIdentityManifest"];
expectedPartSHA256 = candidateHeaderAudit.ExpectedPartSHA256;
if strlength(candidateHeaderAudit.PartsManifestFile) > 0
    hashPaths(end + 1, 1) = candidateHeaderAudit.PartsManifestFile;
    hashRoles(end + 1, 1) = "CandidateDescriptorPartsManifest";
end
if strlength(string(referenceIdentityFile)) > 0
    hashPaths(end + 1, 1) = string(referenceIdentityFile);
    hashRoles(end + 1, 1) = "ReferenceIdentityManifest";
end
if strlength(string(missingnessInputFile)) > 0
    hashPaths(end + 1, 1) = string(missingnessInputFile);
    hashRoles(end + 1, 1) = "SuppliedMissingnessSummary";
end

fileName = strings(numel(hashPaths), 1);
fileBytes = zeros(numel(hashPaths), 1);
sha256 = strings(numel(hashPaths), 1);
for fileIndex = 1:numel(hashPaths)
    fileInformation = dir(hashPaths(fileIndex));
    fileName(fileIndex) = string(fileInformation.name);
    fileBytes(fileIndex) = fileInformation.bytes;
    if computeInputSHA256
        fprintf('  SHA-256 %d/%d: %s\n', ...
            fileIndex, numel(hashPaths), fileInformation.name);
        sha256(fileIndex) = compute_file_sha256(hashPaths(fileIndex));
        if strlength(candidateHeaderAudit.PartsManifestFile) > 0 && ...
                fileIndex <= numel(expectedPartSHA256)
            assert(strcmpi(sha256(fileIndex), expectedPartSHA256(fileIndex)), ...
                'mdl:PartsChecksum', 'Descriptor part SHA-256 mismatch: %s', hashPaths(fileIndex));
        end
    else
        sha256(fileIndex) = "NOT_COMPUTED";
    end
end
inputHashTable = table(hashRoles, fileName, fileBytes, sha256, ...
    'VariableNames', {'Role', 'FileName', 'Bytes', 'SHA256'});
writetable(inputHashTable, inputHashFile, ...
    'FileType', 'text', 'Delimiter', '\t');

backgroundRows = double( ...
    partitionMetadata.BackgroundRowsInDrawOrder(:));
backgroundNames = string(partitionTable.DragonName(backgroundRows));
isBackground = logical(partitionMetadata.IsBackground(:));
isScreeningHoldout = logical( ...
    partitionMetadata.IsScreeningHoldout(:));
isExcluded = logical(partitionMetadata.IsExcluded(:));
partitionGroup = string(partitionTable.PartitionGroup);

partitionMetadata.DeduplicationSummary = deduplicationSummary;
partitionMetadata.PropertyDescriptorIndices = ...
    propertyDescriptorIndices;
partitionMetadata.CandidatePropertyReadAudit = ...
    candidatePropertyReadAudit;
partitionMetadata.PartitionTableFile = partitionTableFile;
partitionMetadata.BackgroundTableFile = backgroundTableFile;
partitionMetadata.HoldoutTableFile = holdoutTableFile;
partitionMetadata.ExcludedTableFile = excludedTableFile;
partitionMetadata.PropertySummaryFile = propertySummaryFile;

save(partitionMatFile, ...
    'partitionMetadata', 'deduplicationSummary', ...
    'backgroundRows', 'backgroundNames', ...
    'isBackground', 'isScreeningHoldout', ...
    'isExcluded', 'partitionGroup', ...
    'referenceDragonNames', 'referenceDisplayNames', ...
    'referenceGroups', '-v7.3');

finishedAt = datetime('now', 'TimeZone', 'local');
datasetMetadata = struct();
datasetMetadata.Version = 1;
datasetMetadata.CreatedAt = char(finishedAt, ...
    'yyyy-MM-dd''T''HH:mm:ssXXX');
datasetMetadata.Pipeline = [ ...
    'stable-identifier global deduplication; configurable background; ' ...
    'mutually exclusive background and formal holdout'];
datasetMetadata.ProjectRootAtCreation = projectRoot;
datasetMetadata.CandidateDescriptorFileName = ...
    localBaseName(candidateDescriptorFile);
datasetMetadata.ReferenceDescriptorFileName = ...
    localBaseName(referenceDescriptorFile);
datasetMetadata.CandidateManifestFileName = ...
    localBaseName(candidateManifestFile);
datasetMetadata.ReferenceIdentityFileName = ...
    localBaseName(referenceIdentityFile);
datasetMetadata.MissingnessSummaryFileName = ...
    localBaseName(missingnessOutputFile);
datasetMetadata.PartitionMatFileName = ...
    localBaseName(partitionMatFile);
datasetMetadata.PartitionTableFileName = ...
    localBaseName(partitionTableFile);
datasetMetadata.BackgroundTableFileName = ...
    localBaseName(backgroundTableFile);
datasetMetadata.HoldoutTableFileName = ...
    localBaseName(holdoutTableFile);
datasetMetadata.CandidateCount = candidateCount;
datasetMetadata.ReferenceCount = referenceCount;
datasetMetadata.InputDescriptorCount = descriptorCount;
datasetMetadata.OriginalDescriptorHeaders = ...
    candidateDescriptorHeaders;
datasetMetadata.ReferenceDragonNames = referenceDragonNames;
datasetMetadata.ReferenceDisplayNames = referenceDisplayNames;
datasetMetadata.ReferenceGroups = referenceGroups;
datasetMetadata.EligibleUniqueCandidateCount = ...
    partitionMetadata.EligibleUniqueCount;
datasetMetadata.BackgroundTrainingCount = ...
    partitionMetadata.BackgroundCount;
datasetMetadata.ScreeningHoldoutCount = ...
    partitionMetadata.ScreeningHoldoutCount;
datasetMetadata.ExcludedCount = partitionMetadata.ExcludedCount;
datasetMetadata.DuplicateNonRepresentativeExcludedCount = ...
    partitionMetadata.DuplicateNonRepresentativeExcludedCount;
datasetMetadata.MissingIdentifierExcludedCount = ...
    partitionMetadata.MissingIdentifierExcludedCount;
datasetMetadata.ReferenceOverlapExcludedCount = ...
    partitionMetadata.ReferenceOverlapExcludedCount;
datasetMetadata.StableIdentifierColumn = ...
    char(stableIdentifierColumn);
datasetMetadata.DuplicateTieBreakColumns = ...
    duplicateTieBreakColumns;
datasetMetadata.BackgroundSelectionMode = ...
    char(backgroundSelectionMode);
datasetMetadata.BackgroundSizeMode = char(backgroundSizeMode);
datasetMetadata.BackgroundFraction = backgroundFraction;
datasetMetadata.BackgroundFixedCountParameter = ...
    backgroundFixedCount;
datasetMetadata.BackgroundMaximumCount = ...
    backgroundMaximumCount;
datasetMetadata.MinimumFormalHoldoutCount = ...
    minimumFormalHoldoutCount;
datasetMetadata.BackgroundRandomSeed = backgroundRandomSeed;
datasetMetadata.MatchingPropertyNames = propertyNamesUsed;
datasetMetadata.DataPartitionIsMutuallyExclusive = true;
datasetMetadata.DeduplicationUsesPreexistingRowIndex = false;
datasetMetadata.SourceRowRole = ...
    deduplicationSummary.SourceRowRole;
datasetMetadata.InputSHA256Computed = computeInputSHA256;
datasetMetadata.InputHashTable = inputHashTable;
datasetMetadata.MATLABVersion = version;
datasetMetadata.ComputerArchitecture = computer;
datasetMetadata.CandidateHeaderAudit = candidateHeaderAudit;
datasetMetadata.ReferenceHeaderAudit = referenceHeaderAudit;
datasetMetadata.ReferenceReadAudit = referenceReadAudit;
datasetMetadata.CandidateMissingnessAudit = ...
    candidateMissingnessAudit;
datasetMetadata.ElapsedSeconds = seconds(finishedAt - startedAt);
save(metadataMatFile, 'datasetMetadata', '-v7.3');

overview = struct();
overview.GeneratedAt = datasetMetadata.CreatedAt;
overview.CandidateRows = candidateCount;
overview.ReferenceRows = referenceCount;
overview.InputDescriptorColumns = descriptorCount;
overview.StableIdentifierColumn = char(stableIdentifierColumn);
overview.UniqueStableIdentifiers = ...
    deduplicationSummary.UniqueCandidateIdentifierCount;
overview.DuplicateNonRepresentativesExcluded = ...
    datasetMetadata.DuplicateNonRepresentativeExcludedCount;
overview.MissingIdentifiersExcluded = ...
    datasetMetadata.MissingIdentifierExcludedCount;
overview.ReferenceOverlapsExcluded = ...
    datasetMetadata.ReferenceOverlapExcludedCount;
overview.EligibleUniqueCandidates = ...
    datasetMetadata.EligibleUniqueCandidateCount;
overview.BackgroundSelectionMode = ...
    datasetMetadata.BackgroundSelectionMode;
overview.BackgroundSizeMode = datasetMetadata.BackgroundSizeMode;
overview.BackgroundTrainingRows = ...
    datasetMetadata.BackgroundTrainingCount;
overview.FormalScreeningRows = ...
    datasetMetadata.ScreeningHoldoutCount;
overview.PartitionIsMutuallyExclusive = true;
overview.InputSHA256Computed = computeInputSHA256;
overview.ElapsedSeconds = datasetMetadata.ElapsedSeconds;
write_json(overviewJsonFile, overview);

statusFolder = paths.Status;
if ~isfolder(statusFolder)
    mkdir(statusFolder);
end
statusFile = fullfile(statusFolder, '00_prepare_dataset_complete.txt');
fileIdentifier = fopen(statusFile, 'w', 'n', 'UTF-8');
assert(fileIdentifier >= 0, 'Cannot create Step 00 status file.');
cleanupStatus = onCleanup(@() fclose(fileIdentifier));
fprintf(fileIdentifier, ...
    ['COMPLETE\nCandidateRows=%d\nReferenceRows=%d\n' ...
     'DescriptorColumns=%d\nEligibleUniqueRows=%d\n' ...
     'BackgroundRows=%d\nFormalRows=%d\nExcludedRows=%d\n' ...
     'BackgroundSelectionMode=%s\nBackgroundSizeMode=%s\n' ...
     'InputSHA256Computed=%d\nElapsedSeconds=%.3f\n'], ...
    candidateCount, referenceCount, descriptorCount, ...
    datasetMetadata.EligibleUniqueCandidateCount, ...
    datasetMetadata.BackgroundTrainingCount, ...
    datasetMetadata.ScreeningHoldoutCount, ...
    datasetMetadata.ExcludedCount, ...
    datasetMetadata.BackgroundSelectionMode, ...
    datasetMetadata.BackgroundSizeMode, ...
    computeInputSHA256, datasetMetadata.ElapsedSeconds);
clear cleanupStatus

fprintf('\n============================================================\n');
fprintf('STEP 00 complete: deduplication and partitions frozen.\n');
fprintf('Candidates: %d; references: %d; descriptors: %d.\n', ...
    candidateCount, referenceCount, descriptorCount);
fprintf('Training background: %d; holdout: %d; excluded: %d.\n', ...
    datasetMetadata.BackgroundTrainingCount, ...
    datasetMetadata.ScreeningHoldoutCount, ...
    datasetMetadata.ExcludedCount);
fprintf('Background mode: %s; count mode: %s.\n', ...
    datasetMetadata.BackgroundSelectionMode, ...
    datasetMetadata.BackgroundSizeMode);
fprintf('Deduplication audit: %s\n', deduplicationAuditFile);
fprintf('Holdout manifest: %s\n', holdoutTableFile);
fprintf('Dataset metadata: %s\n', metadataMatFile);
fprintf('Next: run step01_preprocess_descriptors.\n');
fprintf('============================================================\n\n');

outputs = struct('MetadataFile', metadataMatFile, 'PartitionFile', partitionMatFile, 'HoldoutFile', holdoutTableFile);
end

function fileName = localBaseName(filePath)

if strlength(string(filePath)) == 0
    fileName = '';
    return;
end
[~, baseName, extension] = fileparts(filePath);
fileName = [baseName, extension];
end
