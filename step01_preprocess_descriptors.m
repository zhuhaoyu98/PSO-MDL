function outputs = step01_preprocess_descriptors(configInput)
%STEP01_PREPROCESS_DESCRIPTORS Impute and scale a common descriptor space.
%   Run after Step 00; settings are in functions/pso_mdl_config.m.
%   An optional configuration structure can specify a separate run.
%
%   Input: raw descriptors, fixed partitions and descriptor-availability counts.
%   Output: data01 = X_R (nReference-by-p), data02 = X_B (nBackground-by-p),
%   plus the retained columns, background medians and scaling divisors.
%   Rows are compounds and columns are descriptors. Target fields denote the
%   reference compounds, not measured response values in a calibration model.

%% 1. Configuration and upstream inputs
root = fileparts(mfilename('fullpath'));
addpath(root);
addpath(fullfile(root, 'functions'));
if nargin < 1, configInput = "formal"; end
cfg = resolve_pso_mdl_config(configInput);
paths = pso_mdl_paths(cfg);
partitionFiles = fullfile(paths.Cache, 'dataset_partition.mat');
datasetMetadataFiles = fullfile(paths.Cache, 'dataset_metadata.mat');
auditDir = paths.Audit;
targetOutputFile = fullfile(paths.Cache, 'data01_model.mat');
backgroundOutputFile = fullfile(paths.Cache, 'data02_background.mat');
metadataOutputFile = fullfile(paths.Cache, 'preprocess_metadata.mat');
descriptorAuditFile = fullfile(auditDir, 'descriptor_preprocess_audit.tsv');
overviewJsonFile = fullfile(auditDir, 'preprocess_overview.json');
assert_output_available(metadataOutputFile, cfg.Output.Overwrite);
startedAt = datetime('now', 'TimeZone', 'local');
maxGlobalCandidateMissingRate = cfg.Preprocessing.MaximumCandidateMissingRate;
weightFactor = cfg.Preprocessing.WeightFactor;
nearZeroThreshold = cfg.Preprocessing.NearZeroThreshold;
scaleSampleStride = cfg.Preprocessing.ScaleSampleStride;
chunkRows = cfg.IO.PreprocessingChunkRows;
progressInterval = cfg.IO.ProgressInterval;
partitionMatFile = resolve_input_file( ...
    partitionFiles, 'Step 00 partition MAT');
datasetMetadataFile = resolve_input_file( ...
    datasetMetadataFiles, 'Step 00 dataset metadata MAT');

datasetContents = load(datasetMetadataFile, 'datasetMetadata');
assert(isfield(datasetContents, 'datasetMetadata'), ...
    'dataset_metadata.mat is missing datasetMetadata.');
datasetMetadata = datasetContents.datasetMetadata;
if isfolder(cfg.Input.CandidateDescriptors)
    candidateDescriptorFile = cfg.Input.CandidateDescriptors;
else
    candidateDescriptorFile = resolve_input_file( ...
        cfg.Input.CandidateDescriptors, 'Candidate descriptor TXT or part directory');
end
referenceDescriptorFile = resolve_input_file( ...
    cfg.Input.ReferenceDescriptors, 'Reference descriptor TXT');
missingnessSummaryFile = resolve_input_file( ...
    fullfile(paths.Cache, 'descriptor_missingness_dataset.tsv'), ...
    'Step 00 descriptor missingness summary');

%% 2. Check partition membership and common descriptor order
expectedDescriptorCount = ...
    double(datasetMetadata.InputDescriptorCount);
expectedReferenceRows = double(datasetMetadata.ReferenceCount);
expectedCandidateRows = double(datasetMetadata.CandidateCount);
expectedBackgroundRows = ...
    double(datasetMetadata.BackgroundTrainingCount);
expectedHoldoutRows = ...
    double(datasetMetadata.ScreeningHoldoutCount);
expectedExcludedRows = double(datasetMetadata.ExcludedCount);

partitionContents = load(partitionMatFile, ...
    'isBackground', ...
    'isExcluded', ...
    'isScreeningHoldout', ...
    'backgroundRows', 'backgroundNames', ...
    'partitionMetadata');

requiredPartitionVariables = { ...
    'isBackground', ...
    'isExcluded', ...
    'isScreeningHoldout', ...
    'backgroundRows', 'backgroundNames', ...
    'partitionMetadata'};
for fieldIndex = 1:numel(requiredPartitionVariables)
    assert(isfield(partitionContents, ...
        requiredPartitionVariables{fieldIndex}), ...
        'Partition MAT is missing variable: %s.', ...
        requiredPartitionVariables{fieldIndex});
end

isBackground = logical(partitionContents.isBackground(:));
isExcluded = logical(partitionContents.isExcluded(:));
isHoldout = logical(partitionContents.isScreeningHoldout(:));
backgroundRows = double(partitionContents.backgroundRows(:));
expectedBackgroundNames = ...
    string(partitionContents.backgroundNames(:));
partitionMetadata = partitionContents.partitionMetadata;

assert(numel(isBackground) == expectedCandidateRows, ...
    'Partition candidate count differs from %d.', expectedCandidateRows);
assert(sum(isBackground) == expectedBackgroundRows, ...
    'Training background count differs from %d.', expectedBackgroundRows);
assert(sum(isExcluded) == expectedExcludedRows, ...
    'Step 00 exclusion count differs from %d.', expectedExcludedRows);
assert(sum(isHoldout) == expectedHoldoutRows, ...
    'Holdout candidate count differs from %d.', expectedHoldoutRows);
assert(numel(backgroundRows) == expectedBackgroundRows && ...
    numel(unique(backgroundRows)) == expectedBackgroundRows, ...
    'Background rows must contain %d unique indices.', expectedBackgroundRows);
assert(isequal(find(isBackground), sort(backgroundRows)), ...
    'Background mask disagrees with selectedRowsInDrawOrder.');
assert(~any(isBackground & isExcluded) && ...
    ~any(isBackground & isHoldout) && ...
    ~any(isExcluded & isHoldout) && ...
    all(isBackground | isExcluded | isHoldout), ...
    'Candidate partitions are not mutually exclusive and exhaustive.');

missingOptions = detectImportOptions(missingnessSummaryFile, ...
    'FileType', 'text', 'Delimiter', '\t', ...
    'VariableNamingRule', 'preserve');
missingnessTable = readtable(missingnessSummaryFile, missingOptions);
requiredMissingVariables = [ ...
    "DescriptorIndex", "DescriptorName", ...
    "CandidateMissingCount", "CandidateInfCount"];
assert(all(ismember(requiredMissingVariables, ...
    string(missingnessTable.Properties.VariableNames))), ...
    'Missingness summary lacks required fields.');
assert(height(missingnessTable) == expectedDescriptorCount, ...
    'Missingness summary requires %d rows.', expectedDescriptorCount);
assert(isequal(double(missingnessTable.DescriptorIndex), ...
    (1:expectedDescriptorCount).'), ...
    'DescriptorIndex must equal 1:number of input descriptors.');

summaryDescriptorNames = string(missingnessTable.DescriptorName);
candidateMissingCount = ...
    double(missingnessTable.CandidateMissingCount).';
candidateInfCount = ...
    double(missingnessTable.CandidateInfCount).';
candidateMissingRate = ...
    candidateMissingCount / expectedCandidateRows;

%% 3. Descriptor-availability filtering
% Library-wide missingness is an availability criterion. The background alone
% supplies the numerical imputation and scaling estimates used below.
withinGlobalMissingRate = ...
    candidateMissingRate <= maxGlobalCandidateMissingRate;
hasFiniteCandidateValue = ...
    candidateMissingCount + candidateInfCount < expectedCandidateRows;
hasNoCandidateInfinity = candidateInfCount == 0;
candidateEligibilityMask = ...
    withinGlobalMissingRate & ...
    hasFiniteCandidateValue & ...
    hasNoCandidateInfinity;

fprintf('Raw descriptor count: %d\n', expectedDescriptorCount);
fprintf('Candidate-library missing rate > %.1f%%: %d\n', ...
    100 * maxGlobalCandidateMissingRate, ...
    nnz(~withinGlobalMissingRate));
fprintf('Passed candidate-library availability checks: %d\n\n', ...
    nnz(candidateEligibilityMask));

fprintf('[1/2] Reading %d references and %d descriptors...\n', ...
    expectedReferenceRows, expectedDescriptorCount);
[referenceRaw, targetNames, targetDescriptorNames, targetReadAudit] = ...
    read_descriptor_rows( ...
    string(referenceDescriptorFile), ...
    (1:expectedReferenceRows).', ...
    expectedReferenceRows, expectedDescriptorCount, ...
    min(chunkRows, expectedReferenceRows), ...
    expectedReferenceRows);

fprintf('\n[2/2] Scanning %d candidates to extract %d background rows...\n', ...
    expectedCandidateRows, expectedBackgroundRows);
[backgroundRaw, backgroundNames, candidateDescriptorNames, ...
    candidateReadAudit] = read_descriptor_rows( ...
    string(candidateDescriptorFile), ...
    backgroundRows, expectedCandidateRows, ...
    expectedDescriptorCount, chunkRows, progressInterval);

assert(isequal(targetDescriptorNames, candidateDescriptorNames), ...
    'Reference and candidate descriptor headers disagree.');
assert(isequal(targetDescriptorNames(:), summaryDescriptorNames(:)), ...
    'Descriptor header disagrees with missingness summary.');
assert(isequal(backgroundNames, expectedBackgroundNames), ...
    'Extracted background DragonName disagrees with Step 00 partition.');

descriptorNames = string(targetDescriptorNames(:).');
referenceRaw = double(referenceRaw);
backgroundRaw = double(backgroundRaw);

targetNaNCount = sum(isnan(referenceRaw), 1);
targetInfCount = sum(isinf(referenceRaw), 1);
targetNonfiniteCount = sum(~isfinite(referenceRaw), 1);
backgroundNaNCount = sum(isnan(backgroundRaw), 1);
backgroundInfCount = sum(isinf(backgroundRaw), 1);
backgroundNonfiniteCount = sum(~isfinite(backgroundRaw), 1);

hasFiniteTargetValue = ...
    targetNonfiniteCount < expectedReferenceRows;
globalEligibilityMask = ...
    candidateEligibilityMask & hasFiniteTargetValue;

referenceRaw(~isfinite(referenceRaw)) = NaN;
backgroundRaw(~isfinite(backgroundRaw)) = NaN;

%% 4. Background-median imputation
% Use the same fitted column medians for reference, background and later screening.
eligibleIndices = find(globalEligibilityMask);
backgroundEligible = backgroundRaw(:, eligibleIndices);
imputationValuesEligible = median( ...
    backgroundEligible, 1, 'omitmissing');
hasFiniteBackgroundMedian = isfinite(imputationValuesEligible);

trainingEligibilityMask = globalEligibilityMask;
trainingEligibilityMask( ...
    eligibleIndices(~hasFiniteBackgroundMedian)) = false;
modelInputIndices = find(trainingEligibilityMask);

referenceModelInput = referenceRaw(:, modelInputIndices);
backgroundModelInput = backgroundRaw(:, modelInputIndices);
imputationValuesModel = median( ...
    backgroundModelInput, 1, 'omitmissing');
assert(all(isfinite(imputationValuesModel)), ...
    'Some descriptors cannot be imputed from background medians.');

backgroundImputedValueCount = 0;
targetImputedValueCount = 0;
for columnIndex = 1:numel(modelInputIndices)
    missingBackground = ...
        isnan(backgroundModelInput(:, columnIndex));
    missingTarget = ...
        isnan(referenceModelInput(:, columnIndex));

    backgroundImputedValueCount = ...
        backgroundImputedValueCount + nnz(missingBackground);
    targetImputedValueCount = ...
        targetImputedValueCount + nnz(missingTarget);

    backgroundModelInput(missingBackground, columnIndex) = ...
        imputationValuesModel(columnIndex);
    referenceModelInput(missingTarget, columnIndex) = ...
        imputationValuesModel(columnIndex);
end
assert(all(isfinite(backgroundModelInput), 'all') && ...
    all(isfinite(referenceModelInput), 'all'), ...
    'Nonfinite values remain after median imputation.');

%% 5. Descriptor scaling and name-based emphasis
% s_j = mean_b |x_bj - mean_b(x_bj)|, evaluated after background imputation.
% MATLAB mad(X,0,1) computes this mean absolute deviation, not median AD.
scaleSampleRows = 1:scaleSampleStride:expectedBackgroundRows;
rawMadModel = mad( ...
    backgroundModelInput(scaleSampleRows, :), 0, 1);
normalizationScaleModel = rawMadModel;

weightedIndices = unique( ...
    weighted_descriptor_indices(cellstr(descriptorNames)));
weightedMaskOriginal = false(1, expectedDescriptorCount);
weightedMaskOriginal(weightedIndices) = true;
weightedMaskModelInput = ...
    weightedMaskOriginal(modelInputIndices);
% WeightFactor multiplies the divisor, not the distance. A factor of 0.2
% increases that column's distance contribution by 5 (25 in squared distance).
normalizationScaleModel(weightedMaskModelInput) = ...
    normalizationScaleModel(weightedMaskModelInput) * weightFactor;

% Apply the scale threshold after emphasis; discard unusable columns globally.
retainedWithinModelInput = ...
    isfinite(normalizationScaleModel) & ...
    normalizationScaleModel >= nearZeroThreshold;
retainedIndices = ...
    modelInputIndices(retainedWithinModelInput);
retainedMask = false(1, expectedDescriptorCount);
retainedMask(retainedIndices) = true;

normalizationScale = ...
    normalizationScaleModel(retainedWithinModelInput);
retainedDescriptorHeaders = descriptorNames(retainedMask);
weightedMaskRetained = weightedMaskOriginal(retainedMask);

%% 6. Apply the common transformation: x_scaled,j = x_imputed,j / s_j
% Scaling only: no mean centering, unit-variance scaling or row normalization.
% The same retained columns and divisors are reused unchanged in Step 03.
data01 = referenceModelInput(:, retainedWithinModelInput) ./ ...
    normalizationScale;
data02 = backgroundModelInput(:, retainedWithinModelInput) ./ ...
    normalizationScale;

assert(all(isfinite(data01), 'all') && ...
    all(isfinite(data02), 'all'), ...
    'Nonfinite values remain in final scaled matrices.');
assert(size(data01, 1) == expectedReferenceRows && ...
    size(data02, 1) == expectedBackgroundRows && ...
    size(data01, 2) == size(data02, 2), ...
    'Final data01/data02 dimensions disagree with expected values.');

%% 7. Export matrices and the complete preprocessing specification
% Keep original-column indices so raw screening data map to the same p columns.
excludedByGlobalMissingness = nnz(~withinGlobalMissingRate);
excludedByOtherAvailability = ...
    nnz(withinGlobalMissingRate & ~globalEligibilityMask);
excludedByBackgroundAvailability = ...
    nnz(globalEligibilityMask & ~trainingEligibilityMask);
excludedByNearZeroScale = ...
    nnz(trainingEligibilityMask & ~retainedMask);
retainedFeatureCount = nnz(retainedMask);

imputationValuesOriginal = nan(1, expectedDescriptorCount);
imputationValuesOriginal(modelInputIndices) = ...
    imputationValuesModel;
rawMadScaleOriginal = nan(1, expectedDescriptorCount);
rawMadScaleOriginal(modelInputIndices) = rawMadModel;
normalizationScaleOriginal = nan(1, expectedDescriptorCount);
normalizationScaleOriginal(modelInputIndices) = ...
    normalizationScaleModel;

backgroundMissingRate = ...
    backgroundNonfiniteCount / expectedBackgroundRows;
targetMissingRate = ...
    targetNonfiniteCount / expectedReferenceRows;

exclusionReason = repmat( ...
    "Retained", expectedDescriptorCount, 1);
exclusionReason(~withinGlobalMissingRate(:)) = ...
    "GlobalCandidateMissingRateAboveThreshold";
exclusionReason(withinGlobalMissingRate(:) & ...
    ~hasFiniteCandidateValue(:)) = ...
    "NoFiniteCandidateValue";
exclusionReason(withinGlobalMissingRate(:) & ...
    hasFiniteCandidateValue(:) & ...
    ~hasNoCandidateInfinity(:)) = ...
    "CandidateInfinityObserved";
exclusionReason(candidateEligibilityMask(:) & ...
    ~hasFiniteTargetValue(:)) = ...
    "NoFiniteValueInReferenceSet";
exclusionReason(globalEligibilityMask(:) & ...
    ~trainingEligibilityMask(:)) = ...
    "NoFiniteMedianInBackgroundSample";
exclusionReason(trainingEligibilityMask(:) & ...
    ~retainedMask(:)) = ...
    "NearZeroOrInvalidScale";

descriptorAuditTable = table( ...
    (1:expectedDescriptorCount).', ...
    descriptorNames(:), ...
    candidateMissingCount(:), ...
    candidateInfCount(:), ...
    candidateMissingRate(:), ...
    targetNaNCount(:), ...
    targetInfCount(:), ...
    targetNonfiniteCount(:), ...
    targetMissingRate(:), ...
    backgroundNaNCount(:), ...
    backgroundInfCount(:), ...
    backgroundNonfiniteCount(:), ...
    backgroundMissingRate(:), ...
    imputationValuesOriginal(:), ...
    rawMadScaleOriginal(:), ...
    normalizationScaleOriginal(:), ...
    weightedMaskOriginal(:), ...
    retainedMask(:), ...
    exclusionReason, ...
    'VariableNames', { ...
    'DescriptorIndex', 'DescriptorName', ...
    'CandidateMissingCount', 'CandidateInfCount', ...
    'CandidateMissingRate', ...
    'ReferenceNaNCount', 'ReferenceInfCount', ...
    'ReferenceNonfiniteCount', 'ReferenceNonfiniteRate', ...
    'BackgroundNaNCount', 'BackgroundInfCount', ...
    'BackgroundNonfiniteCount', ...
    'BackgroundNonfiniteRate', ...
    'BackgroundMedianImputationValue', ...
    'RawMAD', 'NormalizationScale', ...
    'WeightedDescriptor', 'RetainedForModel', ...
    'ExclusionReason'});
writetable(descriptorAuditTable, descriptorAuditFile, ...
    'FileType', 'text', 'Delimiter', '\t');

finishedAt = datetime('now', 'TimeZone', 'local');

preprocessMetadata = struct();
preprocessMetadata.Version = 4;
preprocessMetadata.CreatedAt = char(finishedAt, ...
    'yyyy-MM-dd''T''HH:mm:ssXXX');
preprocessMetadata.Pipeline = sprintf([ ...
    'Dragon%d; Step00 %s background (n=%d); ' ...
    'background-only median imputation/mean-AD scale fit; reference n=%d'], ...
    expectedDescriptorCount, ...
    datasetMetadata.BackgroundSelectionMode, ...
    expectedBackgroundRows, expectedReferenceRows);
preprocessMetadata.DatasetMetadataFile = datasetMetadataFile;
preprocessMetadata.ReferenceDescriptorFile = ...
    referenceDescriptorFile;
preprocessMetadata.CandidateDescriptorFile = ...
    candidateDescriptorFile;
preprocessMetadata.MissingnessSummaryFile = ...
    missingnessSummaryFile;
preprocessMetadata.PartitionMatFile = partitionMatFile;
preprocessMetadata.SourceFile = candidateDescriptorFile;
preprocessMetadata.TargetCount = expectedReferenceRows;
preprocessMetadata.ReferenceGroup = ...
    string(datasetMetadata.ReferenceGroups(:));
preprocessMetadata.CandidateCount = expectedCandidateRows;
preprocessMetadata.BackgroundTrainingCount = ...
    expectedBackgroundRows;
preprocessMetadata.ExcludedCandidateCount = expectedExcludedRows;
preprocessMetadata.DuplicateNonRepresentativeExcludedCount = ...
    datasetMetadata.DuplicateNonRepresentativeExcludedCount;
preprocessMetadata.MissingIdentifierExcludedCount = ...
    datasetMetadata.MissingIdentifierExcludedCount;
preprocessMetadata.ReferenceOverlapExcludedCount = ...
    datasetMetadata.ReferenceOverlapExcludedCount;
preprocessMetadata.ScreeningHoldoutCount = ...
    expectedHoldoutRows;
preprocessMetadata.BackgroundPartitionFrozen = true;
preprocessMetadata.PreprocessingFitUsesTargets = false;
preprocessMetadata.PreprocessingFitUsesFormalCandidates = false;
preprocessMetadata.IdentifierColumnCount = 2;
preprocessMetadata.OriginalDescriptorHeaders = ...
    descriptorNames;
preprocessMetadata.InputDescriptorCount = ...
    expectedDescriptorCount;
preprocessMetadata.MaxGlobalCandidateMissingRate = ...
    maxGlobalCandidateMissingRate;
preprocessMetadata.GlobalEligibilityMask = ...
    globalEligibilityMask;
preprocessMetadata.TrainingEligibilityMask = ...
    trainingEligibilityMask;
preprocessMetadata.ImputationMethod = sprintf( ...
    ['column median fitted only on the %d frozen ' ...
     'background representatives'], expectedBackgroundRows);
preprocessMetadata.ImputationValuesOriginal = ...
    imputationValuesOriginal;
preprocessMetadata.BackgroundMissingCount = ...
    backgroundNonfiniteCount;
preprocessMetadata.TargetMissingCount = ...
    targetNonfiniteCount;
preprocessMetadata.BackgroundImputedValueCount = ...
    backgroundImputedValueCount;
preprocessMetadata.TargetImputedValueCount = ...
    targetImputedValueCount;
preprocessMetadata.SampleStride = scaleSampleStride;
preprocessMetadata.WeightFactor = weightFactor;
preprocessMetadata.NearZeroThreshold = nearZeroThreshold;
% Retain historical field names for MAT compatibility; values are mean AD.
preprocessMetadata.ScaleDefinition = 'mean(abs(X-mean(X)),1), MATLAB mad(X,0,1)';
preprocessMetadata.RawMadScale = rawMadScaleOriginal;
preprocessMetadata.RawMadScaleOriginal = ...
    rawMadScaleOriginal;
preprocessMetadata.NormalizationScaleOriginal = ...
    normalizationScaleOriginal;
preprocessMetadata.RetainedMask = retainedMask;
preprocessMetadata.RetainedDescriptorHeaders = ...
    retainedDescriptorHeaders;
preprocessMetadata.NormalizationScale = ...
    normalizationScale;
preprocessMetadata.WeightedMaskOriginal = ...
    weightedMaskOriginal;
preprocessMetadata.WeightedMaskRetained = ...
    weightedMaskRetained;
preprocessMetadata.RemovedIndices = find(~retainedMask);
preprocessMetadata.OutputDescriptorCount = ...
    retainedFeatureCount;
preprocessMetadata.InputRowCount = ...
    expectedReferenceRows + expectedBackgroundRows;
preprocessMetadata.BackgroundRowsInDrawOrder = ...
    backgroundRows;
preprocessMetadata.TargetNames = targetNames;
preprocessMetadata.BackgroundNames = backgroundNames;
preprocessMetadata.TargetReadAudit = targetReadAudit;
preprocessMetadata.CandidateReadAudit = candidateReadAudit;
preprocessMetadata.DescriptorAuditFile = ...
    descriptorAuditFile;
preprocessMetadata.ElapsedSeconds = ...
    seconds(finishedAt - startedAt);

save(targetOutputFile, ...
    'data01', 'targetNames', '-v7.3');
save(backgroundOutputFile, ...
    'data02', 'backgroundNames', 'backgroundRows', '-v7.3');
save(metadataOutputFile, 'preprocessMetadata', '-v7.3');

overview = struct();
overview.GeneratedAt = preprocessMetadata.CreatedAt;
overview.ReferenceRows = size(data01, 1);
overview.BackgroundTrainingRows = size(data02, 1);
overview.ExcludedCandidateRows = expectedExcludedRows;
overview.DuplicateNonRepresentativeRowsExcluded = ...
    datasetMetadata.DuplicateNonRepresentativeExcludedCount;
overview.MissingIdentifierRowsExcluded = ...
    datasetMetadata.MissingIdentifierExcludedCount;
overview.ReferenceOverlapRowsExcluded = ...
    datasetMetadata.ReferenceOverlapExcludedCount;
overview.FormalScreeningRows = expectedHoldoutRows;
overview.RawDescriptorColumns = expectedDescriptorCount;
overview.ExcludedByGlobalMissingness = ...
    excludedByGlobalMissingness;
overview.ExcludedByOtherAvailabilityChecks = ...
    excludedByOtherAvailability;
overview.ExcludedByBackgroundSampleAvailability = ...
    excludedByBackgroundAvailability;
overview.ExcludedByNearZeroOrInvalidScale = ...
    excludedByNearZeroScale;
overview.RetainedModelFeatures = ...
    retainedFeatureCount;
overview.BackgroundImputedValues = ...
    backgroundImputedValueCount;
overview.TargetImputedValues = ...
    targetImputedValueCount;
overview.TargetOutputFile = targetOutputFile;
overview.BackgroundOutputFile = backgroundOutputFile;
overview.MetadataOutputFile = metadataOutputFile;
overview.DescriptorAuditFile = descriptorAuditFile;
overview.ElapsedSeconds = ...
    preprocessMetadata.ElapsedSeconds;
write_json(overviewJsonFile, overview);

statusDir = paths.Status;
if ~isfolder(statusDir)
    mkdir(statusDir);
end
statusFile = fullfile(statusDir, '01_preprocess_complete.txt');
fileId = fopen(statusFile, 'w', 'n', 'UTF-8');
assert(fileId >= 0, 'Cannot create preprocessing status file: %s', statusFile);
cleanupFile = onCleanup(@() fclose(fileId));
fprintf(fileId, ...
    ['COMPLETE\nReferenceRows=%d\nBackgroundRows=%d\n' ...
     'FormalRows=%d\nRawDescriptors=%d\n' ...
     'RetainedDescriptors=%d\nBackgroundImputedValues=%d\n' ...
     'TargetImputedValues=%d\nElapsedSeconds=%.3f\n'], ...
    size(data01, 1), size(data02, 1), expectedHoldoutRows, ...
    expectedDescriptorCount, retainedFeatureCount, ...
    backgroundImputedValueCount, targetImputedValueCount, ...
    preprocessMetadata.ElapsedSeconds);
clear cleanupFile

fprintf('\n============================================================\n');
fprintf('Preprocessing complete.\n');
fprintf('Reference matrix data01: %d x %d\n', ...
    size(data01, 1), size(data01, 2));
fprintf('Background matrix data02: %d x %d\n', ...
    size(data02, 1), size(data02, 2));
fprintf('Holdout candidates: %d (parameters frozen; not ranked yet)\n', ...
    expectedHoldoutRows);
fprintf('Raw descriptors: %d; retained: %d.\n', ...
    expectedDescriptorCount, retainedFeatureCount);
fprintf('Background cells imputed: %d; reference cells imputed: %d.\n', ...
    backgroundImputedValueCount, targetImputedValueCount);
fprintf('Elapsed time: %.1f s.\n', ...
    preprocessMetadata.ElapsedSeconds);
fprintf('Next: run step02_train_models.\n');
fprintf('============================================================\n\n');

outputs = struct('ReferenceMatrix', targetOutputFile, 'BackgroundMatrix', backgroundOutputFile, 'MetadataFile', metadataOutputFile);
end
