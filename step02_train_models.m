function outputs = step02_train_models(configInput)
%STEP02_TRAIN_MODELS Run independent sign-encoded PSO models and summarize optimization stability.
%   With no input, use the formal profile from functions/pso_mdl_config.m.
%   CONFIGINPUT can also be a profile name or a configuration structure.
%   Results are written only under the configured output directory.
root = fileparts(mfilename('fullpath'));
addpath(root);
addpath(fullfile(root, 'functions'));
if nargin < 1, configInput = "formal"; end
cfg = resolve_pso_mdl_config(configInput);
paths = pso_mdl_paths(cfg);
resultDir = paths.Results;
statusDir = paths.Status;
targetInputFile = resolve_input_file( ...
    fullfile(paths.Cache, 'data01_model.mat'), 'Step 01 reference matrix');
backgroundInputFile = resolve_input_file( ...
    fullfile(paths.Cache, 'data02_background.mat'), 'Step 01 background matrix');
metadataInputFile = fullfile(paths.Cache, 'preprocess_metadata.mat');
assert_output_available(fullfile(resultDir, 'models.mat'), cfg.Output.Overwrite);
% Set the computational thread limit before constructing any distance context.
% Restore the caller's session setting when Step 02 finishes or raises an error.
previousThreadLimit = maxNumCompThreads;
restoreThreadLimit = onCleanup(@() maxNumCompThreads(previousThreadLimit));
executionEnvironment = configure_numerical_execution(cfg);
seeds = cfg.PSO.Seeds;
populationSize = cfg.PSO.PopulationSize;
generationCount = cfg.PSO.GenerationCount;
scheduleHorizon = cfg.PSO.ScheduleHorizon;
inertiaWeightStart = cfg.PSO.InertiaWeightStart;
inertiaWeightEnd = cfg.PSO.InertiaWeightEnd;
cognitiveCoefficient = cfg.PSO.CognitiveCoefficient;
socialCoefficient = cfg.PSO.SocialCoefficient;
particleMutationRateStart = cfg.PSO.ParticleMutationRateStart;
particleMutationRateEnd = cfg.PSO.ParticleMutationRateEnd;
particleMutationRateFloor = cfg.PSO.ParticleMutationRateFloor;
featureMutationRateStart = cfg.PSO.FeatureMutationRateStart;
featureMutationRateEnd = cfg.PSO.FeatureMutationRateEnd;
featureMutationRateFloor = cfg.PSO.FeatureMutationRateFloor;
mutationSchedulePower = cfg.PSO.MutationSchedulePower;
mutationQuenchStartFraction = cfg.PSO.MutationQuenchStartFraction;
mutationNoiseScale = cfg.PSO.MutationNoiseScale;
velocityLimit = cfg.PSO.VelocityLimit;
positionLimit = cfg.PSO.PositionLimit;
stallWindow = cfg.PSO.StallWindow;
stallRelativeTolerance = cfg.PSO.StallRelativeTolerance;
distanceEpsilon = cfg.PSO.DistanceEpsilon;
targetContents = load( ...
    targetInputFile, 'data01', 'targetNames');
backgroundContents = load(backgroundInputFile, ...
    'data02', 'backgroundRows', 'backgroundNames');
targetData = targetContents.data01;
backgroundData = backgroundContents.data02;
assert(size(targetData, 1) >= 2 && size(targetData, 2) >= 1, ...
    'Reference matrix must be at least 2-by-1.');
assert(size(backgroundData, 1) >= 2 && ...
    size(backgroundData, 2) == size(targetData, 2), ...
    'Background requires at least two rows and equal feature count to reference.');
assert(all(isfinite(targetData), 'all') && ...
    all(isfinite(backgroundData), 'all'), ...
    'Step 01 matrices contain NaN or Inf.');

context = build_fitness_context( ...
    targetData, backgroundData, distanceEpsilon);
modelCount = numel(seeds);
assert(modelCount >= 2 && numel(unique(seeds)) == modelCount, ...
    'At least two distinct random seeds are required.');
featureCount = context.FeatureCount;

bestMasks = false(modelCount, featureCount);
bestFitness = zeros(modelCount, 1);
bestComparisonKey = zeros(modelCount, 1);
bestD1 = zeros(modelCount, 1);
bestD2 = zeros(modelCount, 1);
bestSeparation = zeros(modelCount, 1);
bestRelativeGap = zeros(modelCount, 1);
bestD2OverD1 = zeros(modelCount, 1);
bestP = zeros(modelCount, 1);
selectedFeatureCount = zeros(modelCount, 1);
runtimeSeconds = zeros(modelCount, 1);
lastImprovementGeneration = zeros(modelCount, 1);
monotonicViolationCount = zeros(modelCount, 1);
finalWindowRelativeImprovement = zeros(modelCount, 1);
convergedByStallCriterion = false(modelCount, 1);

bestFitnessByGeneration = ...
    zeros(modelCount, generationCount);
bestComparisonKeyByGeneration = ...
    zeros(modelCount, generationCount);
selectedFeatureCountByGeneration = ...
    zeros(modelCount, generationCount);
bestD1ByGeneration = ...
    zeros(modelCount, generationCount);
bestD2ByGeneration = ...
    zeros(modelCount, generationCount);
bestRelativeGapByGeneration = ...
    zeros(modelCount, generationCount);
bestPByGeneration = ...
    zeros(modelCount, generationCount);
% Each seed changes only initialization/search randomness, not the dataset or metric.
totalTimer = tic;
for idxModel = 1:modelCount
    modelTimer = tic;
    modelResult = run_sign_pso(context, ...
        'PopulationSize', populationSize, ...
        'GenerationCount', generationCount, ...
        'ScheduleHorizon', scheduleHorizon, ...
        'RandomSeed', seeds(idxModel), ...
        'InertiaWeightStart', inertiaWeightStart, ...
        'InertiaWeightEnd', inertiaWeightEnd, ...
        'CognitiveCoefficient', cognitiveCoefficient, ...
        'SocialCoefficient', socialCoefficient, ...
        'ParticleMutationRateStart', particleMutationRateStart, ...
        'ParticleMutationRateEnd', particleMutationRateEnd, ...
        'ParticleMutationRateFloor', particleMutationRateFloor, ...
        'FeatureMutationRateStart', featureMutationRateStart, ...
        'FeatureMutationRateEnd', featureMutationRateEnd, ...
        'FeatureMutationRateFloor', featureMutationRateFloor, ...
        'MutationSchedulePower', mutationSchedulePower, ...
        'MutationQuenchStartFraction', mutationQuenchStartFraction, ...
        'MutationNoiseScale', mutationNoiseScale, ...
        'VelocityLimit', velocityLimit, ...
        'PositionLimit', positionLimit, ...
        'StallWindow', stallWindow, ...
        'StallRelativeTolerance', stallRelativeTolerance, ...
        'Verbose', false);

    bestMasks(idxModel, :) = modelResult.BestMask;
    bestFitness(idxModel) = modelResult.BestFitness;
    bestComparisonKey(idxModel) = modelResult.BestComparisonKey;
    bestD1(idxModel) = modelResult.BestD1;
    bestD2(idxModel) = modelResult.BestD2;
    bestSeparation(idxModel) = modelResult.BestSeparation;
    bestRelativeGap(idxModel) = modelResult.BestRelativeGap;
    bestD2OverD1(idxModel) = modelResult.BestD2OverD1;
    bestP(idxModel) = modelResult.BestP;
    selectedFeatureCount(idxModel) = ...
        modelResult.BestSelectedFeatureCount;
    runtimeSeconds(idxModel) = modelResult.RuntimeSeconds;
    lastImprovementGeneration(idxModel) = ...
        modelResult.LastImprovementGeneration;
    monotonicViolationCount(idxModel) = ...
        modelResult.MonotonicViolationCount;
    finalWindowRelativeImprovement(idxModel) = ...
        modelResult.FinalWindowRelativeImprovement;
    convergedByStallCriterion(idxModel) = ...
        modelResult.ConvergedByStallCriterion;
    bestFitnessByGeneration(idxModel, :) = ...
        modelResult.BestFitnessByGeneration(:).';
    bestComparisonKeyByGeneration(idxModel, :) = ...
        modelResult.BestComparisonKeyByGeneration(:).';
    selectedFeatureCountByGeneration(idxModel, :) = ...
        modelResult.SelectedFeatureCountByGeneration(:).';
    bestD1ByGeneration(idxModel, :) = ...
        modelResult.BestD1ByGeneration(:).';
    bestD2ByGeneration(idxModel, :) = ...
        modelResult.BestD2ByGeneration(:).';
    bestRelativeGapByGeneration(idxModel, :) = ...
        modelResult.BestRelativeGapByGeneration(:).';
    bestPByGeneration(idxModel, :) = ...
        modelResult.BestPByGeneration(:).';
    assert(modelResult.MonotonicViolationCount == 0, ...
        'Seed %d has a best-so-far fitness monotonicity violation.', seeds(idxModel));
    historyTolerance = 1e-12 * max(1, ...
        max(abs(modelResult.BestFitnessByGeneration)));
    assert(abs(modelResult.BestFitnessByGeneration(end) ...
        - modelResult.BestFitness) <= historyTolerance, ...
        'Seed %d final history value disagrees with BestFitness.', ...
        seeds(idxModel));
    assert(modelResult.ScheduleHorizon == scheduleHorizon ...
        && abs(modelResult.InertiaWeightStart - inertiaWeightStart) < eps ...
        && abs(modelResult.InertiaWeightEnd - inertiaWeightEnd) < eps ...
        && abs(modelResult.CognitiveCoefficient - cognitiveCoefficient) < eps ...
        && abs(modelResult.SocialCoefficient - socialCoefficient) < eps ...
        && abs(modelResult.ParticleMutationRateStart - particleMutationRateStart) < eps ...
        && abs(modelResult.ParticleMutationRateEnd - particleMutationRateEnd) < eps ...
        && abs(modelResult.ParticleMutationRateFloor - particleMutationRateFloor) < eps ...
        && abs(modelResult.FeatureMutationRateStart - featureMutationRateStart) < eps ...
        && abs(modelResult.FeatureMutationRateEnd - featureMutationRateEnd) < eps ...
        && abs(modelResult.FeatureMutationRateFloor - featureMutationRateFloor) < eps ...
        && abs(modelResult.MutationSchedulePower - mutationSchedulePower) < eps ...
        && abs(modelResult.MutationQuenchStartFraction - mutationQuenchStartFraction) < eps ...
        && abs(modelResult.MutationNoiseScale - mutationNoiseScale) < eps ...
        && abs(modelResult.VelocityLimit - velocityLimit) < eps ...
        && abs(modelResult.PositionLimit - positionLimit) < eps ...
        && modelResult.StallWindow == stallWindow ...
        && abs(modelResult.StallRelativeTolerance - stallRelativeTolerance) < eps, ...
        'Seed %d PSO parameters disagree with frozen Step 02 settings.', seeds(idxModel));

    fprintf(['Seed %2d/%2d (%d): F=%d, fitness %.8g, ' ...
        'relative gap %.8g, P %.8g, %.2f s\n'], ...
        idxModel, modelCount, seeds(idxModel), ...
        selectedFeatureCount(idxModel), bestFitness(idxModel), ...
        bestRelativeGap(idxModel), bestP(idxModel), toc(modelTimer));
end
optimizationSeconds = toc(totalTimer);

modelSummaryTable = table(seeds, selectedFeatureCount, bestFitness, ...
    bestD1, bestD2, bestSeparation, bestRelativeGap, bestD2OverD1, ...
    bestP, runtimeSeconds, ...
    lastImprovementGeneration, monotonicViolationCount, ...
    finalWindowRelativeImprovement, convergedByStallCriterion, ...
    'VariableNames', {'Seed', 'SelectedFeatureCount', 'BestFitness', ...
    'D1', 'D2', 'D2MinusD1', 'RelativeGap', 'D2OverD1Diagnostic', ...
    'P', 'RuntimeSeconds', ...
    'LastImprovementGeneration', 'MonotonicViolationCount', ...
    'FinalWindowRelativeImprovement', 'ConvergedByStallCriterion'});
writetable(modelSummaryTable, fullfile(resultDir, ...
    'model_summary.tsv'), ...
    'FileType', 'text', 'Delimiter', '\t');

% Descriptor overlap is diagnostic and does not select or reweight models.
featureSelectionCount = sum(bestMasks, 1).';
featureSelectionFrequency = featureSelectionCount ./ modelCount;
descriptorIndex = (1:featureCount).';
featureFrequencyTable = table(descriptorIndex, ...
    featureSelectionCount, featureSelectionFrequency, ...
    'VariableNames', {'RetainedDescriptorIndex', ...
    'SelectionCount', 'SelectionFrequency'});

if isfile(metadataInputFile)
    metadataContents = load(metadataInputFile);
    if isfield(metadataContents, 'preprocessMetadata') ...
            && isfield(metadataContents.preprocessMetadata, ...
                'RetainedDescriptorHeaders')
        descriptorNames = string(metadataContents.preprocessMetadata ...
            .RetainedDescriptorHeaders(:));
        if numel(descriptorNames) == featureCount
            featureFrequencyTable.DescriptorName = descriptorNames;
        end
    end
end
featureFrequencyTable = sortrows(featureFrequencyTable, ...
    {'SelectionFrequency', 'RetainedDescriptorIndex'}, ...
    {'descend', 'ascend'});
writetable(featureFrequencyTable, fullfile(resultDir, ...
    'descriptor_selection_frequency.tsv'), ...
    'FileType', 'text', 'Delimiter', '\t');

featureIntersection = double(bestMasks) * double(bestMasks).';
featureUnion = selectedFeatureCount + selectedFeatureCount.' ...
    - featureIntersection;
featureJaccard = featureIntersection ./ featureUnion;
upperTriangleMask = triu(true(modelCount), 1);
pairwiseFeatureJaccard = featureJaccard(upperTriangleMask);

summary = struct();
summary.Version = 6;
summary.ExecutionEnvironment = executionEnvironment;
summary.MethodLabel = sprintf( ...
    ['PSO-MDL -((D2-D1)/(D1+epsilon))*F*P, %d seeds, ' ...
     '%d particles x %d generations'], ...
    modelCount, populationSize, generationCount);
summary.ObjectiveDefinition = context.ObjectiveDefinition;
summary.PAggregation = context.PAggregation;
summary.PDefinition = context.PDefinition;
summary.PRange = context.PRange;
% Comparison keys are numerical provenance, never reported as mean-scale J.
summary.ComparisonKeyDefinition = modelResult.ComparisonKeyDefinition;
summary.ComparisonKeyScale = modelResult.ComparisonKeyScale;
summary.ComparisonRule = modelResult.ComparisonRule;
summary.DistanceEpsilon = distanceEpsilon;
summary.D1ValidityRule = context.D1ValidityRule;
summary.SearchDefinition = [ ...
    'continuous bounded latent positions; selected when position>0; ' ...
    'elementwise r1/r2; x=x+v; fixed-horizon linearly decreasing inertia; ' ...
    'quadratically decaying sign-flip mutation with a nonzero late-stage floor; ' ...
    'no per-generation magnitude reset'];
summary.PopulationSize = populationSize;
summary.GenerationCount = generationCount;
summary.ScheduleHorizon = scheduleHorizon;
summary.InertiaWeightStart = inertiaWeightStart;
summary.InertiaWeightEnd = inertiaWeightEnd;
summary.CognitiveCoefficient = cognitiveCoefficient;
summary.SocialCoefficient = socialCoefficient;
summary.ParticleMutationRateStart = particleMutationRateStart;
summary.ParticleMutationRateEnd = particleMutationRateEnd;
summary.ParticleMutationRateFloor = particleMutationRateFloor;
summary.FeatureMutationRateStart = featureMutationRateStart;
summary.FeatureMutationRateEnd = featureMutationRateEnd;
summary.FeatureMutationRateFloor = featureMutationRateFloor;
summary.MutationSchedulePower = mutationSchedulePower;
summary.MutationQuenchStartFraction = mutationQuenchStartFraction;
summary.MutationNoiseScale = mutationNoiseScale;
summary.VelocityLimit = velocityLimit;
summary.PositionLimit = positionLimit;
summary.StallWindow = stallWindow;
summary.StallRelativeTolerance = stallRelativeTolerance;
summary.ReferenceIndex = context.ReferenceIndex;
summary.ReferenceName = char(targetContents.targetNames(context.ReferenceIndex));
summary.TargetCount = context.TargetCountIncludingReference;
summary.BackgroundCount = context.BackgroundCount;
summary.FeatureCount = featureCount;
summary.ModelCount = modelCount;
summary.Seeds = seeds.';
summary.MeanSelectedFeatureCount = mean(selectedFeatureCount);
summary.MinimumSelectedFeatureCount = min(selectedFeatureCount);
summary.MaximumSelectedFeatureCount = max(selectedFeatureCount);
summary.MeanBestFitness = mean(bestFitness);
summary.BestFitnessAcrossSeeds = min(bestFitness);
summary.WorstFitnessAcrossSeeds = max(bestFitness);
summary.MeanFeaturePairwiseJaccard = mean(pairwiseFeatureJaccard);
summary.MinimumFeaturePairwiseJaccard = min(pairwiseFeatureJaccard);
summary.FeatureUnionCount = sum(any(bestMasks, 1));
summary.FeatureIntersectionCount = sum(all(bestMasks, 1));
summary.MedianLastImprovementGeneration = ...
    median(lastImprovementGeneration);
summary.MaximumLastImprovementGeneration = ...
    max(lastImprovementGeneration);
summary.TotalMonotonicViolationCount = ...
    sum(monotonicViolationCount);
summary.MedianFinalWindowRelativeImprovement = ...
    median(finalWindowRelativeImprovement);
summary.MaximumFinalWindowRelativeImprovement = ...
    max(finalWindowRelativeImprovement);
summary.ConvergedSeedCount = sum(convergedByStallCriterion);
summary.ConvergedSeedFraction = mean(convergedByStallCriterion);
summary.OptimizationRuntimeSeconds = optimizationSeconds;
summary.ScheduleQuenchStartGeneration = 1 + ceil( ...
    mutationQuenchStartFraction * (scheduleHorizon - 1));
summary.PostScheduleVerificationGenerations = generationCount - scheduleHorizon;
summary.CreatedAt = char(datetime('now', 'Format', "yyyyMMdd'T'HHmmss"));

generation = (1:generationCount).';
fitnessMedian = median(bestFitnessByGeneration, 1).';
fitnessQ1 = column_percentile(bestFitnessByGeneration, 25).';
fitnessQ3 = column_percentile(bestFitnessByGeneration, 75).';
descriptorMedian = median(selectedFeatureCountByGeneration, 1).';
descriptorQ1 = column_percentile( ...
    selectedFeatureCountByGeneration, 25).';
descriptorQ3 = column_percentile( ...
    selectedFeatureCountByGeneration, 75).';

figureSourceTable = table(generation, ...
    fitnessMedian, fitnessQ1, fitnessQ3, ...
    descriptorMedian, descriptorQ1, descriptorQ3, ...
    'VariableNames', {'PSOIteration', ...
    'MedianBestFitness', 'BestFitnessQ1', 'BestFitnessQ3', ...
    'MedianSelectedDescriptorCount', ...
    'SelectedDescriptorCountQ1', 'SelectedDescriptorCountQ3'});
figureSourceFile = fullfile(resultDir, ...
    'optimization_history.tsv');
writetable(figureSourceTable, figureSourceFile, ...
    'FileType', 'text', 'Delimiter', '\t');

summary.FigureSourceDataFile = figureSourceFile;

save(fullfile(resultDir, ...
    'models.mat'), ...
    'summary', 'modelSummaryTable', 'bestMasks', ...
    'featureSelectionCount', 'featureSelectionFrequency', ...
    'bestFitnessByGeneration', ...
    'bestComparisonKey', 'bestComparisonKeyByGeneration', ...
    'selectedFeatureCountByGeneration', ...
    'bestD1ByGeneration', 'bestD2ByGeneration', ...
    'bestRelativeGapByGeneration', 'bestPByGeneration', ...
    'finalWindowRelativeImprovement', 'convergedByStallCriterion', ...
    'figureSourceTable', ...
    '-v7.3');

write_json(fullfile(resultDir, 'model_summary.json'), summary);
fid = fopen(fullfile(statusDir, '02_complete.txt'), 'wt');
assert(fid >= 0, 'Cannot create Step 02 status file.');
fprintf(fid, 'COMPLETE\nModels=%d\nGenerations=%d\n', modelCount, generationCount);
fclose(fid);
fprintf('STEP 02 COMPLETE: %d models; selected F %d-%d of %d. Run Step 04 for figures.\n', ...
    modelCount, min(selectedFeatureCount), max(selectedFeatureCount), featureCount);

outputs = struct('ModelsFile', fullfile(resultDir, 'models.mat'), 'SummaryFile', fullfile(resultDir, 'model_summary.tsv'));
end
