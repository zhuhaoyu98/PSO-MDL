function spearmanValue = localSpearman(firstValue, secondValue)
firstRank = localOrdinalRank(firstValue);
secondRank = localOrdinalRank(secondValue);
spearmanValue = corr(firstRank, secondRank);
end

function rankValue = localOrdinalRank(value)
[~, order] = sort(value, 'ascend');
rankValue = zeros(size(value));
rankValue(order) = (1:numel(value)).';
end

function mask = localTopKMask(value, K)
[~, order] = sort(value, 'ascend');
mask = false(size(value));
mask(order(1:K)) = true;
end

