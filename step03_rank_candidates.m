function tailPercent = localUpperTailPercent(backgroundValue, queryValue)
% Return 100*mean(backgroundValue > queryValue) for each query distance.
% Ties contribute zero. This candidate statistic is distinct from training P,
% which averages reference-compound percentiles within a descriptor subset.
sortedBackground = sort(double(backgroundValue(:)), 'ascend');
queryValue = double(queryValue(:));
backgroundCount = numel(sortedBackground);

lowerIndex = zeros(size(queryValue));
upperIndex = repmat(backgroundCount + 1, size(queryValue));
while any(upperIndex - lowerIndex > 1)
    middleIndex = floor((lowerIndex + upperIndex) ./ 2);
    active = upperIndex - lowerIndex > 1;
    probeIndex = max(1, min(backgroundCount, middleIndex));
    moveLower = active ...
        & middleIndex >= 1 ...
        & middleIndex <= backgroundCount ...
        & sortedBackground(probeIndex) <= queryValue;
    moveUpper = active & ~moveLower;
    lowerIndex(moveLower) = middleIndex(moveLower);
    upperIndex(moveUpper) = middleIndex(moveUpper);
end
countLessThanOrEqual = lowerIndex;
tailPercent = 100 .* ...
    (backgroundCount - countLessThanOrEqual) ./ backgroundCount;
end
