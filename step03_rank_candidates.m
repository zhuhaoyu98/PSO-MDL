function outputs = step03_rank_candidates(configInput)
%STEP03_RANK_CANDIDATES Rank the frozen holdout by equally weighted mean single-model ranks.
%   With no input, use the formal profile from functions/pso_mdl_config.m.
%   CONFIGINPUT can also be a profile name or a configuration structure.
%   Results are written only under the configured output directory.
root = fileparts(mfilename('fullpath'));
addpath(root);
addpath(fullfile(root, 'functions'));
if nargin < 1, configInput = "formal"; end
cfg = resolve_pso_mdl_config(configInput);
paths = pso_mdl_paths(cfg);
resultDir = paths.Results;
figureDir = paths.Figures;
statusDir = paths.Status;
datasetMetadataFiles = fullfile(paths.Cache, 'dataset_metadata.mat');
partitionFiles = fullfile(paths.Cache, 'dataset_partition.mat');
holdoutManifestFiles = fullfile(paths.Cache, 'screening_holdout.tsv');
assert_output_available(fullfile(resultDir, 'candidate_ranking.mat'), cfg.Output.Overwrite);
expectedReferenceIndex = cfg.Ranking.ExpectedReferenceIndex;
stabilityTopK = cfg.Ranking.StabilityTopK;
stabilityCurveTopKValues = cfg.Ranking.StabilityCurveTopK(:).';
rankingFigureTopCandidateCount = cfg.Ranking.FigureTopCandidateCount;
dragonReadChunkRows = cfg.IO.ScoringChunkRows;
dragonProgressInterval = cfg.IO.ScoringProgressInterval;
showFiguresOnScreen = cfg.Figures.Show;
datasetMetadataFile = resolve_input_file( ...
    datasetMetadataFiles, 'Step 00 dataset metadata');
partitionMatFile = resolve_input_file( ...
    partitionFiles, 'Step 00 partition MAT');
holdoutManifestFile = resolve_input_file( ...
    holdoutManifestFiles, 'Step 00 holdout manifest TSV');

datasetContents = load(datasetMetadataFile, 'datasetMetadata');
assert(isfield(datasetContents, 'datasetMetadata'), ...
    'dataset_metadata.mat is missing datasetMetadata.');
datasetMetadata = datasetContents.datasetMetadata;

dragonCandidateFile = cfg.Input.CandidateDescriptors;
expectedCandidateRows = double(datasetMetadata.CandidateCount);
expectedDescriptorCount = ...
    double(datasetMetadata.InputDescriptorCount);
expectedTargetRows = double(datasetMetadata.ReferenceCount);
expectedBackgroundRows = ...
    double(datasetMetadata.BackgroundTrainingCount);
expectedHoldoutRows = ...
    double(datasetMetadata.ScreeningHoldoutCount);
expectedExcludedRows = double(datasetMetadata.ExcludedCount);
assert(isfile(dragonCandidateFile) || isfolder(dragonCandidateFile), ...
    'Candidate descriptor TXT or part directory required by Step 00 is missing: %s', ...
    dragonCandidateFile);
stabilityTopK = min(stabilityTopK, expectedHoldoutRows);
assert(stabilityTopK >= 1, 'At least one holdout candidate is required.');
assert(all(isfinite(stabilityCurveTopKValues)) ...
    && all(stabilityCurveTopKValues >= 1) ...
    && all(stabilityCurveTopKValues == floor(stabilityCurveTopKValues)), ...
    'stabilityCurveTopKValues must contain positive integers.');
stabilityCurveTopKValues = unique([ ...
    stabilityCurveTopKValues(stabilityCurveTopKValues <= ...
    expectedHoldoutRows), stabilityTopK], 'sorted');
rankingFigureTopCandidateCount = min( ...
    rankingFigureTopCandidateCount, expectedHoldoutRows);
assert(rankingFigureTopCandidateCount >= 1 ...
    && rankingFigureTopCandidateCount == ...
    floor(rankingFigureTopCandidateCount), ...
    'rankingFigureTopCandidateCount must be a positive integer.');

targetFile = resolve_input_file( ...
    dir(fullfile(paths.Cache, 'data01_model.mat')), ...
    'Preprocessed reference matrix');
backgroundFile = resolve_input_file( ...
    dir(fullfile(paths.Cache, 'data02_background.mat')), ...
    'Preprocessed training background matrix');
metadataFile = resolve_input_file( ...
    dir(fullfile(paths.Cache, 'preprocess_metadata.mat')), ...
    'Frozen preprocessing metadata');
psoFile = resolve_input_file( ...
    dir(fullfile(resultDir, ...
    'models.mat')), ...
    'Step 02 multiseed PSO-MDL models');

targetContents = load(targetFile, 'data01', 'targetNames');
backgroundContents = load(backgroundFile, ...
    'data02', 'backgroundRows', 'backgroundNames');
metadataContents = load(metadataFile, 'preprocessMetadata');
psoContents = load(psoFile, ...
    'bestMasks', 'modelSummaryTable', ...
    'featureSelectionFrequency', 'summary');

targetData = double(targetContents.data01);
targetNames = string(targetContents.targetNames(:));
backgroundData = double(backgroundContents.data02);
backgroundRows = double(backgroundContents.backgroundRows(:));
backgroundNames = string(backgroundContents.backgroundNames(:));
preprocessMetadata = metadataContents.preprocessMetadata;
bestMasksFull = logical(psoContents.bestMasks);
seeds = double(psoContents.modelSummaryTable.Seed(:));
featureSelectionFrequency = double( ...
    psoContents.featureSelectionFrequency(:));
assert(isfield(psoContents, 'summary') ...
    && isfield(psoContents.summary, 'DistanceEpsilon') ...
    && isfield(psoContents.summary, 'ObjectiveDefinition'), ...
    ['Step 02 lacks DistanceEpsilon or ObjectiveDefinition;' ...
     ' run step02_train_models with the current implementation.']);
distanceEpsilon = double(psoContents.summary.DistanceEpsilon);
assert(isfield(psoContents.summary, 'PAggregation') ...
    && strcmp(psoContents.summary.PAggregation, 'mean_non_medoid'), ...
    ['Step 02 must use mean non-medoid P. Supply compatible mean-P models ' ...
     'or run step02_train_models with this configuration.']);

[targetCount, retainedFeatureCount] = size(targetData);
[modelCount, maskFeatureCount] = size(bestMasksFull);
assert(targetCount == expectedTargetRows, ...
    'Reference count differs from Step 00 count %d.', expectedTargetRows);
assert(size(backgroundData, 1) == expectedBackgroundRows, ...
    'Training background count differs from Step 00 count %d.', expectedBackgroundRows);
assert(size(backgroundData, 2) == retainedFeatureCount, ...
    'Background and reference feature counts disagree.');
assert(modelCount >= 2 && numel(seeds) == modelCount, ...
    'Mean-rank aggregation requires at least two PSO models with saved seeds.');
assert(maskFeatureCount == retainedFeatureCount, ...
    'PSO mask width disagrees with Step 01 retained feature count.');
assert(numel(featureSelectionFrequency) == retainedFeatureCount, ...
    'Descriptor-frequency length disagrees with retained feature count.');
assert(all(sum(bestMasksFull, 2) > 0), ...
    'A PSO model has selected no descriptors.');

context = build_fitness_context( ...
    targetData, backgroundData, distanceEpsilon);
assert(strcmp(context.ObjectiveDefinition, ...
    psoContents.summary.ObjectiveDefinition), ...
    'Step 02 objective definition disagrees with this implementation.');
if ~isempty(expectedReferenceIndex)
    assert(context.ReferenceIndex == expectedReferenceIndex, ...
        'Expected reference medoid at row %d; found row %d.', ...
        expectedReferenceIndex, context.ReferenceIndex);
end
referenceName = targetNames(context.ReferenceIndex);

% Read only the union of saved feature masks; preserve original descriptor order.
modelUnionMaskFull = any(bestMasksFull, 1);
unionModelIndices = find(modelUnionMaskFull);
unionFeatureCount = numel(unionModelIndices);
assert(unionFeatureCount >= 1, 'Descriptor union across models is empty.');
modelMasksUnion = bestMasksFull(:, unionModelIndices);

retainedOriginalIndices = find( ...
    logical(preprocessMetadata.RetainedMask(:)));
assert(numel(retainedOriginalIndices) == retainedFeatureCount, ...
    'RetainedMask disagrees with model feature count.');
unionOriginalIndices = retainedOriginalIndices(unionModelIndices);
expectedUnionNames = string( ...
    preprocessMetadata.RetainedDescriptorHeaders(unionModelIndices));
imputationValues = double( ...
    preprocessMetadata.ImputationValuesOriginal(unionOriginalIndices));
normalizationScale = double( ...
    preprocessMetadata.NormalizationScaleOriginal(unionOriginalIndices));
referenceVectorUnion = ...
    targetData(context.ReferenceIndex, unionModelIndices);

fprintf(['PSO-MDL mean-rank screening: reference medoid=%s (row %d);' ...
    ' %d models, descriptor union=%d/%d.\n'], ...
    referenceName, context.ReferenceIndex, modelCount, ...
    unionFeatureCount, retainedFeatureCount);

totalTimer = tic;
[allModelDistance, allDragonNames, ...
    selectedDescriptorNames, dragonAudit] = ...
    score_candidates_streaming( ...
    string(dragonCandidateFile), ...
    double(unionOriginalIndices(:)), ...
    imputationValues, normalizationScale, ...
    referenceVectorUnion, modelMasksUnion, ...
    expectedCandidateRows, expectedDescriptorCount, ...
    dragonReadChunkRows, dragonProgressInterval);

assert(isequal(selectedDescriptorNames(:), expectedUnionNames(:)), ...
    'Descriptor names or order disagree with frozen Step 01 metadata.');

% Verify streamed preprocessing against every frozen training-background distance.
expectedBackgroundDistance = sqrt( ...
    context.BackgroundSquaredDelta * double(bestMasksFull).');
observedBackgroundDistance = ...
    allModelDistance(backgroundRows, :);
maximumBackgroundDistanceError = max(abs( ...
    observedBackgroundDistance - expectedBackgroundDistance), [], 'all');
assert(maximumBackgroundDistanceError <= 1e-8, ...
    ['Streaming preprocessing failed to reproduce training distances;' ...
     ' maximum absolute error %.17g.'], maximumBackgroundDistanceError);
assert(isequal(allDragonNames(backgroundRows), backgroundNames), ...
    'Streaming background names or order disagree with Step 01.');
fprintf(['Frozen preprocessing/distance regression passed: %d x %d,' ...
    ' maximum absolute error %.3g.\n'], ...
    expectedBackgroundRows, modelCount, maximumBackgroundDistanceError);

partitionContents = load(partitionMatFile, ...
    'isBackground', 'isExcluded', 'isScreeningHoldout', ...
    'backgroundRows');
isBackground = logical(partitionContents.isBackground(:));
isExcluded = logical(partitionContents.isExcluded(:));
isHoldout = logical(partitionContents.isScreeningHoldout(:));
partitionBackgroundRows = double( ...
    partitionContents.backgroundRows(:));

assert(numel(isHoldout) == expectedCandidateRows, ...
    'Frozen partition total row count is incorrect.');
assert(sum(isBackground) == expectedBackgroundRows, ...
    'Frozen training-background count is incorrect.');
assert(sum(isExcluded) == expectedExcludedRows, ...
    'Frozen exclusion count is incorrect.');
assert(sum(isHoldout) == expectedHoldoutRows, ...
    'Frozen holdout count is incorrect.');
assert(~any(isBackground & isExcluded) ...
    && ~any(isBackground & isHoldout) ...
    && ~any(isExcluded & isHoldout) ...
    && all(isBackground | isExcluded | isHoldout), ...
    'Background, exclusions, and holdout are not mutually exclusive and exhaustive.');
assert(isequal(backgroundRows, partitionBackgroundRows), ...
    'Background matrix order disagrees with Step 00 partition.');

holdoutGlobalRow = find(isHoldout);
modelDistance = allModelDistance(isHoldout, :);
holdoutDragonNames = allDragonNames(isHoldout);
clear allModelDistance allDragonNames observedBackgroundDistance

holdoutManifest = readtable(holdoutManifestFile, ...
    'FileType', 'text', 'Delimiter', '\t', 'TextType', 'string');
assert(height(holdoutManifest) == expectedHoldoutRows, ...
    'Holdout manifest row count is incorrect.');
assert(isequal(double(holdoutManifest.SourceRow), ...
    double(holdoutGlobalRow)), ...
    'Holdout manifest SourceRow disagrees with frozen partition.');
assert(isequal(string(holdoutManifest.DragonName), ...
    holdoutDragonNames), ...
    'Holdout manifest DragonName disagrees with descriptor TXT.');

rankByCandidate = zeros(expectedHoldoutRows, modelCount, 'uint32');
meanBackgroundTailPercentile = zeros(expectedHoldoutRows, 1);
rankingTimer = tic;
for modelIndex = 1:modelCount
    [~, currentOrder] = sortrows( ...
        [modelDistance(:, modelIndex), ...
        double(holdoutGlobalRow)], [1, 2]);
    currentRank = zeros(expectedHoldoutRows, 1, 'uint32');
    currentRank(currentOrder) = uint32((1:expectedHoldoutRows).');
    rankByCandidate(:, modelIndex) = currentRank;

    currentTail = localUpperTailPercent( ...
        expectedBackgroundDistance(:, modelIndex), ...
        modelDistance(:, modelIndex));
    meanBackgroundTailPercentile = ...
        meanBackgroundTailPercentile + currentTail ./ modelCount;

    if mod(modelIndex, 8) == 0 || modelIndex == modelCount
        fprintf('  Holdout ranks: %d/%d models, %.1f s elapsed.\n', ...
            modelIndex, modelCount, toc(rankingTimer));
    end
end
clear modelDistance

% Aggregate ordinal ranks with equal weights; source rows break exact ties.
rankSummary = aggregate_candidate_ranks(rankByCandidate, holdoutGlobalRow);
rankDouble = rankSummary.DoubleRanks;
meanRank = rankSummary.MeanRank;
medianRank = rankSummary.MedianRank;
rankSD = rankSummary.RankSD;
bestRank = rankSummary.BestRank;
worstRank = rankSummary.WorstRank;
rankP10 = rankSummary.RankP10;
rankP90 = rankSummary.RankP90;
meanRankOrder = rankSummary.Order;
finalRank = rankSummary.FinalRank;
clear rankSummary
% Top-K recurrence describes model variability, not activity probability.
topKMembership = rankDouble <= stabilityTopK;
topKSelectionCount = sum(topKMembership, 2);
topKSelectionFrequency = topKSelectionCount ./ modelCount;
finalTopKMask = finalRank <= stabilityTopK;

modelTopKOverlapCount = sum( ...
    topKMembership & finalTopKMask, 1).';
modelTopKOverlapFraction = ...
    modelTopKOverlapCount ./ stabilityTopK;
modelTopKJaccardWithFinal = modelTopKOverlapCount ./ ...
    (2 .* stabilityTopK - modelTopKOverlapCount);
modelTopKOverlapTable = table(seeds, ...
    repmat(stabilityTopK, modelCount, 1), ...
    modelTopKOverlapCount, modelTopKOverlapFraction, ...
    modelTopKJaccardWithFinal, ...
    'VariableNames', {'Seed', 'TopK', ...
    'OverlapCountWithMeanRankTopK', ...
    'OverlapFractionOfMeanRankTopK', ...
    'JaccardWithMeanRankTopK'});

upperTriangle = triu(true(modelCount), 1);

[pairModelA, pairModelB] = find(upperTriangle);
pairCount = numel(pairModelA);
curvePointCount = numel(stabilityCurveTopKValues);
pairwiseIntersectionByTopK = zeros(pairCount, curvePointCount);
pairwiseJaccardByTopK = zeros(pairCount, curvePointCount);

for curveIndex = 1:curvePointCount
    currentTopK = stabilityCurveTopKValues(curveIndex);
    currentMembership = sparse( ...
        rankByCandidate <= uint32(currentTopK));
    currentIntersection = full( ...
        currentMembership.' * currentMembership);
    currentUnion = 2 .* currentTopK - currentIntersection;
    currentJaccard = currentIntersection ./ currentUnion;
    pairwiseIntersectionByTopK(:, curveIndex) = ...
        currentIntersection(upperTriangle);
    pairwiseJaccardByTopK(:, curveIndex) = ...
        currentJaccard(upperTriangle);
end

stabilityColumn = find( ...
    stabilityCurveTopKValues == stabilityTopK, 1);
pairwiseTopKJaccard = ...
    pairwiseJaccardByTopK(:, stabilityColumn);

jaccardAtKQ1 = column_percentile( ...
    pairwiseJaccardByTopK, 25);
jaccardAtKMedian = column_percentile( ...
    pairwiseJaccardByTopK, 50);
jaccardAtKQ3 = column_percentile( ...
    pairwiseJaccardByTopK, 75);
jaccardAtKSummaryTable = table( ...
    stabilityCurveTopKValues(:), ...
    repmat(pairCount, curvePointCount, 1), ...
    mean(pairwiseIntersectionByTopK, 1).', ...
    mean(pairwiseJaccardByTopK, 1).', ...
    std(pairwiseJaccardByTopK, 0, 1).', ...
    jaccardAtKQ1(:), jaccardAtKMedian(:), jaccardAtKQ3(:), ...
    min(pairwiseJaccardByTopK, [], 1).', ...
    max(pairwiseJaccardByTopK, [], 1).', ...
    'VariableNames', {'TopK', 'ModelPairCount', ...
    'MeanIntersectionCount', 'MeanJaccard', 'SDJaccard', ...
    'JaccardQ1', 'MedianJaccard', 'JaccardQ3', ...
    'MinimumJaccard', 'MaximumJaccard'});

jaccardAtKPairTable = table( ...
    repelem(stabilityCurveTopKValues(:), pairCount), ...
    repmat(seeds(pairModelA), curvePointCount, 1), ...
    repmat(seeds(pairModelB), curvePointCount, 1), ...
    reshape(pairwiseIntersectionByTopK, [], 1), ...
    reshape(pairwiseJaccardByTopK, [], 1), ...
    'VariableNames', {'TopK', 'SeedA', 'SeedB', ...
    'IntersectionCount', 'JaccardIndex'});

rankingTable = table( ...
    finalRank, holdoutGlobalRow, ...
    string(holdoutManifest.DragonName), ...
    string(holdoutManifest.OriginalTitle), ...
    string(holdoutManifest.ExternalID), ...
    string(holdoutManifest.StableIdentifier), ...
    meanRank, medianRank, rankSD, rankP10, rankP90, ...
    bestRank, worstRank, ...
    topKSelectionCount, topKSelectionFrequency, ...
    meanBackgroundTailPercentile, ...
    double(holdoutManifest.NearestTargetIndex), ...
    string(holdoutManifest.NearestTargetName), ...
    double(holdoutManifest.NearestTargetPropertyDistance), ...
    'VariableNames', { ...
    'Rank', 'SourceRow', 'DragonName', 'OriginalTitle', ...
    'ExternalID', 'StableIdentifier', ...
    'MeanRankAcrossSeeds', 'MedianRankAcrossSeeds', ...
    'RankSDAcrossSeeds', 'RankP10AcrossSeeds', ...
    'RankP90AcrossSeeds', 'BestRankAcrossSeeds', ...
    'WorstRankAcrossSeeds', ...
    'Top1000CountAcrossSeeds', 'Top1000FrequencyAcrossSeeds', ...
    'MeanBackgroundTailPercentileAcrossSeeds', ...
    'NearestReferenceIndexByMatchedProperties', ...
    'NearestReferenceNameByMatchedProperties', ...
    'NearestReferencePropertyDistance'});

rankingTable = sortrows(rankingTable, 'Rank', 'ascend');

fullRankingFile = fullfile(resultDir, ...
    'candidate_ranking.tsv');
top20File = fullfile(resultDir, ...
    'top20.tsv');
top1000File = fullfile(resultDir, ...
    'top1000.tsv');
top10000File = fullfile(resultDir, ...
    'top10000.tsv');
top1000FrequencyFile = fullfile(resultDir, ...
    'topk_frequency.tsv');
modelTopKOverlapFile = fullfile(resultDir, ...
    'topk_model_overlap.tsv');
jaccardAtKSummaryFile = fullfile(resultDir, ...
    'jaccard_at_k_summary.tsv');
jaccardAtKPairFile = fullfile(resultDir, ...
    'jaccard_at_k_pairs.tsv');
topCandidateFigureSourceFile = fullfile(resultDir, ...
    'top_candidates_rank_uncertainty.tsv');
jaccardStabilityFigureBase = fullfile(figureDir, ...
    'candidate_set_stability');
rankUncertaintyFigureBase = fullfile(figureDir, ...
    'top_candidates_rank_uncertainty');
rankingStabilityLegendFile = fullfile(resultDir, ...
    'ranking_figure_legends.txt');
matFile = fullfile(resultDir, ...
    'candidate_ranking.mat');
jsonFile = fullfile(resultDir, ...
    'ranking_summary.json');

writetable(rankingTable, fullRankingFile, ...
    'FileType', 'text', 'Delimiter', '\t');
top20Count = min(20, height(rankingTable));
top1000Count = min(1000, height(rankingTable));
top10000Count = min(10000, height(rankingTable));
writetable(rankingTable(1:top20Count, :), top20File, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(rankingTable(1:top1000Count, :), top1000File, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(rankingTable(1:top10000Count, :), top10000File, ...
    'FileType', 'text', 'Delimiter', '\t');

top1000FrequencyTable = rankingTable(1:top1000Count, :);
top1000FrequencyTable = sortrows(top1000FrequencyTable, ...
    {'Top1000CountAcrossSeeds', 'MeanRankAcrossSeeds', 'Rank'}, ...
    {'descend', 'ascend', 'ascend'});
top1000FrequencyTable.StabilityOrder = ...
    (1:height(top1000FrequencyTable)).';
top1000FrequencyTable = movevars(top1000FrequencyTable, ...
    'StabilityOrder', 'Before', 'Rank');
writetable(top1000FrequencyTable, top1000FrequencyFile, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(modelTopKOverlapTable, modelTopKOverlapFile, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(jaccardAtKSummaryTable, jaccardAtKSummaryFile, ...
    'FileType', 'text', 'Delimiter', '\t');
writetable(jaccardAtKPairTable, jaccardAtKPairFile, ...
    'FileType', 'text', 'Delimiter', '\t');

rankingFigureCount = min( ...
    rankingFigureTopCandidateCount, height(rankingTable));
topCandidateFigureTable = rankingTable(1:rankingFigureCount, { ...
    'Rank', 'SourceRow', 'DragonName', 'ExternalID', ...
    'MeanRankAcrossSeeds', 'MedianRankAcrossSeeds', ...
    'RankSDAcrossSeeds', 'RankP10AcrossSeeds', ...
    'RankP90AcrossSeeds', 'BestRankAcrossSeeds', ...
    'WorstRankAcrossSeeds', 'Top1000CountAcrossSeeds', ...
    'Top1000FrequencyAcrossSeeds'});
writetable(topCandidateFigureTable, topCandidateFigureSourceFile, ...
    'FileType', 'text', 'Delimiter', '\t');

visibilityOptions = {'off', 'on'};
figureVisibility = visibilityOptions{1 + double(showFiguresOnScreen)};

jaccardFigure = figure('Color', 'w', 'Visible', figureVisibility, ...
    'Units', 'centimeters', 'Position', [2, 2, 12.0, 8.5]);
jaccardAxes = axes(jaccardFigure);
hold(jaccardAxes, 'on');
stabilityX = stabilityCurveTopKValues(:);
iqrPatch = fill(jaccardAxes, ...
    [stabilityX; flipud(stabilityX)], ...
    [jaccardAtKQ1(:); flipud(jaccardAtKQ3(:))], ...
    [86, 180, 233] ./ 255, ...
    'EdgeColor', 'none', 'FaceAlpha', 0.28, ...
    'DisplayName', 'Interquartile range');
medianLine = plot(jaccardAxes, stabilityX, ...
    jaccardAtKMedian(:), '-o', ...
    'Color', [0, 114, 178] ./ 255, ...
    'MarkerFaceColor', [0, 114, 178] ./ 255, ...
    'MarkerEdgeColor', 'w', 'MarkerSize', 4.5, ...
    'LineWidth', 1.5, 'DisplayName', 'Median');
set(jaccardAxes, 'XScale', 'log', 'YLim', [0, 1]);
if isscalar(stabilityX)
    xlim(jaccardAxes, [0.8 .* stabilityX, 1.25 .* stabilityX]);
else

    xlim(jaccardAxes, [ ...
        min(stabilityX) ./ 1.15, max(stabilityX) .* 1.15]);
end
xticks(jaccardAxes, stabilityX);
xticklabels(jaccardAxes, localCompactIntegerLabels(stabilityX));
xlabel(jaccardAxes, 'Top-K threshold');
ylabel(jaccardAxes, 'Pairwise Jaccard index');
legend(jaccardAxes, [medianLine, iqrPatch], ...
    'Location', 'southeast', 'Box', 'off', 'FontSize', 7);
localStyleAxes(jaccardAxes, 'Arial', 8);
hold(jaccardAxes, 'off');
drawnow;
export_publication_figure(jaccardFigure, jaccardStabilityFigureBase, 600);

rankFigure = figure('Color', 'w', 'Visible', figureVisibility, ...
    'Units', 'centimeters', 'Position', [2, 2, 12.0, 10.5]);
rankAxes = axes(rankFigure);
hold(rankAxes, 'on');
candidateY = (1:rankingFigureCount).';
for candidateIndex = 1:rankingFigureCount
    plot(rankAxes, [ ...
        topCandidateFigureTable.BestRankAcrossSeeds(candidateIndex), ...
        topCandidateFigureTable.WorstRankAcrossSeeds(candidateIndex)], ...
        [candidateY(candidateIndex), candidateY(candidateIndex)], '-', ...
        'Color', [0.72, 0.72, 0.72], 'LineWidth', 0.8, ...
        'HandleVisibility', 'off');
    plot(rankAxes, [ ...
        topCandidateFigureTable.RankP10AcrossSeeds(candidateIndex), ...
        topCandidateFigureTable.RankP90AcrossSeeds(candidateIndex)], ...
        [candidateY(candidateIndex), candidateY(candidateIndex)], '-', ...
        'Color', [0, 114, 178] ./ 255, 'LineWidth', 2.2, ...
        'HandleVisibility', 'off');
end

rangeLegend = plot(rankAxes, nan, nan, '-', ...
    'Color', [0.72, 0.72, 0.72], 'LineWidth', 0.8, ...
    'DisplayName', 'Minimum-maximum');
percentileLegend = plot(rankAxes, nan, nan, '-', ...
    'Color', [0, 114, 178] ./ 255, 'LineWidth', 2.2, ...
    'DisplayName', '10th-90th percentile');
meanRankMarker = scatter(rankAxes, ...
    topCandidateFigureTable.MeanRankAcrossSeeds, candidateY, ...
    24, [213, 94, 0] ./ 255, 'filled', ...
    'MarkerEdgeColor', 'w', 'LineWidth', 0.5, ...
    'DisplayName', 'Mean rank');
set(rankAxes, 'XScale', 'log', 'YDir', 'reverse', ...
    'YLim', [0.3, rankingFigureCount + 0.7]);
rankMaximum = max( ...
    topCandidateFigureTable.WorstRankAcrossSeeds);
rankUpperLimit = max(10, 10 .^ ceil(log10(rankMaximum)));
xlim(rankAxes, [0.8, rankUpperLimit]);
yticks(rankAxes, candidateY);
yticklabels(rankAxes, compose('%d', ...
    topCandidateFigureTable.Rank));
xlabel(rankAxes, 'Rank in individual PSO model');
ylabel(rankAxes, 'Final ensemble rank');
legend(rankAxes, [meanRankMarker, percentileLegend, rangeLegend], ...
    'Location', 'southoutside', 'Box', 'off', 'FontSize', 7);
localStyleAxes(rankAxes, 'Arial', 8);
hold(rankAxes, 'off');
drawnow;
export_publication_figure(rankFigure, rankUncertaintyFigureBase, 600);

legendId = fopen(rankingStabilityLegendFile, 'wt');
assert(legendId >= 0, 'Cannot write ranking-stability figure legends.');
legendCleanup = onCleanup(@() fclose(legendId));
fprintf(legendId, [ ...
    'Figure 3. Stability of the Top-K candidate sets across ' ...
    'independent PSO runs. Pairwise Jaccard similarity of the ' ...
    'single-model Top-K candidate sets over multiple K thresholds. ' ...
    'The line denotes the median and the shaded band denotes the ' ...
    'interquartile range across %d model pairs.\n\n' ...
    'Figure 4. Model-specific rank uncertainty for the final ' ...
    'mean-rank Top %d candidates. ' ...
    'Points denote arithmetic mean ranks, thick intervals denote ' ...
    'the 10th-90th percentiles, and thin intervals denote the full ' ...
    'minimum-maximum range across %d independent PSO runs. Lower ' ...
    'ranks indicate higher priority.\n'], ...
    pairCount, rankingFigureCount, modelCount);
clear legendCleanup

summary = struct();
summary.Version = 6;
summary.ObjectiveDefinition = context.ObjectiveDefinition;
summary.PAggregation = context.PAggregation;
summary.PDefinition = context.PDefinition;
summary.PRange = context.PRange;
summary.DistanceEpsilon = context.DistanceEpsilon;
summary.D1ValidityRule = context.D1ValidityRule;
summary.RankingMethod = ...
    'equal-weight arithmetic mean rank across independent PSO models';
summary.RankingTieBreak = ...
    'SourceRow ascending only when MeanRankAcrossSeeds is exactly tied';
summary.ReferenceIndex = context.ReferenceIndex;
summary.ReferenceName = char(referenceName);
