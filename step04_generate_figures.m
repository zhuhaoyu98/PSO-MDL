function rho = localSpearmanAverageTies(firstValue, secondValue)
firstRank = localAverageRank(firstValue);
secondRank = localAverageRank(secondValue);
rho = corr(firstRank, secondRank);
end

function rankValue = localAverageRank(value)
value = double(value(:));
assert(all(isfinite(value)), 'Average-rank input contains NaN or Inf.');
[sortedValue, order] = sort(value, 'ascend');
rankSorted = zeros(size(sortedValue));
startIndex = 1;
while startIndex <= numel(sortedValue)
    endIndex = startIndex;
    while endIndex < numel(sortedValue) ...
            && sortedValue(endIndex + 1) == sortedValue(startIndex)
        endIndex = endIndex + 1;
    end
    averagePosition = (startIndex + endIndex) ./ 2;
    rankSorted(startIndex:endIndex) = averagePosition;
    startIndex = endIndex + 1;
end
rankValue = zeros(size(value));
rankValue(order) = rankSorted;
end

function labels = localCompactIntegerLabels(values)
values = double(values(:));
labels = strings(size(values));
for valueIndex = 1:numel(values)
    if values(valueIndex) >= 1000 ...
            && mod(values(valueIndex), 1000) == 0
        labels(valueIndex) = sprintf('%gk', values(valueIndex) ./ 1000);
    else
        labels(valueIndex) = sprintf('%g', values(valueIndex));
    end
end
end

function yRange = localUpperBoundedRange(observedMinimum, upperBound, padding)
observedMinimum = double(observedMinimum);
lowerBound = max(-1, observedMinimum - padding);
if upperBound == 1
    lowerBound = max(0, lowerBound);
end
if lowerBound >= upperBound
    lowerBound = upperBound - max(padding, 0.01);
end
yRange = [lowerBound, upperBound];
end

function yRange = localRoundedDataRange(values, stepSize)

values = double(values(:));
values = values(isfinite(values));
assert(~isempty(values), 'Cannot determine axis limits from empty data.');
lowerBound = floor(min(values) ./ stepSize) .* stepSize;
upperBound = ceil(max(values) ./ stepSize) .* stepSize;
if lowerBound == upperBound
    lowerBound = lowerBound - stepSize;
    upperBound = upperBound + stepSize;
end
yRange = [lowerBound, upperBound];
end

