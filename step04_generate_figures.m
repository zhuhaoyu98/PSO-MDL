function outputs = step04_generate_figures(configInput, options)
%STEP04_GENERATE_FIGURES Plot this project's completed Step 02/03 results.
%   STEP04_GENERATE_FIGURES defaults to the configured pipeline outputs and
%   recomputes figure/ensemble statistics in results/research/figures.
%   STEP04_GENERATE_FIGURES("saved") explicitly redraws the historical paper
%   bundle in data/paper_results into results/paper_figures instead.
%   Passing CFG also selects pipeline mode. Neither mode retrains models or
%   changes candidate ranks. Missing pipeline data never trigger a saved fallback.
%   DataDirectory, OutputDirectory, Show, Overwrite and Dpi apply to saved mode.
arguments
    configInput = "pipeline"
    options.DataDirectory (1,1) string = ""
    options.OutputDirectory (1,1) string = ""
    options.Show (1,1) logical = false
    options.Overwrite (1,1) logical = false
    options.Dpi (1,1) double {mustBePositive,mustBeFinite} = 600
end
root = fileparts(mfilename('fullpath'));
addpath(root);
addpath(fullfile(root, 'functions'));
if (ischar(configInput) || isstring(configInput)) && isscalar(string(configInput))
    mode = lower(string(configInput));
    if mode == "saved"
        resolve_pso_mdl_config("formal");
        outputs = plot_saved_paper_figures(options.DataDirectory, ...
            options.OutputDirectory, 'Show', options.Show, ...
            'Overwrite', options.Overwrite, 'Dpi', options.Dpi);
        return;
    elseif mode == "pipeline"
        configInput = "formal";
    end
end
cfg = resolve_pso_mdl_config(configInput);
paths = pso_mdl_paths(cfg);
resultDir = paths.Results;
figureDir = paths.Figures;
statusDir = paths.Status;
showFiguresOnScreen = cfg.Figures.Show;
overwriteExistingFigures = cfg.Figures.Overwrite;
figureResolutionDpi = cfg.Figures.Dpi;
figureFontName = cfg.Figures.FontName;
baseFontSizePt = cfg.Figures.PublicationFontSize;
fitnessDisplayScale = cfg.Figures.FitnessDisplayScale;
regularFigureSizeCm = cfg.Figures.RegularSizeCm;
tallFigureSizeCm = cfg.Figures.TallSizeCm;
ensembleSubsetSizesRequested = cfg.Figures.EnsembleSubsetSizes;
ensembleStabilityRepeats = cfg.Figures.EnsembleRepeats;
ensembleStabilityRandomSeed = cfg.Figures.EnsembleRandomSeed;
ensembleTopK = cfg.Figures.EnsembleTopK;
step02FigureSourceFile = resolve_input_file(dir(fullfile(resultDir, ...
    'optimization_history.tsv')), ...
    'Step 02 figure-source TSV');
step02SummaryFile = resolve_input_file(dir(fullfile(resultDir, ...
    'model_summary.json')), ...
    'Step 02 summary JSON');
step02MatFile = resolve_input_file(dir(fullfile(resultDir, ...
    'models.mat')), ...
    'Step 02 model MAT');

step03JaccardSummaryFile = resolve_input_file(dir(fullfile(resultDir, ...
    'jaccard_at_k_summary.tsv')), ...
    'Step 03 Jaccard@K summary TSV');
step03TopCandidateFile = resolve_input_file(dir(fullfile(resultDir, ...
    'top_candidates_rank_uncertainty.tsv')), ...
    'Step 03 top-candidate uncertainty TSV');
step03SummaryFile = resolve_input_file(dir(fullfile(resultDir, ...
    'ranking_summary.json')), ...
    'Step 03 summary JSON');
step03MatFile = resolve_input_file(dir(fullfile(resultDir, ...
    'candidate_ranking.mat')), ...
    'Step 03 candidate-ranking MAT');

step02FigureTable = readtable(step02FigureSourceFile, ...
    'FileType', 'text', 'Delimiter', '\t', ...
    'VariableNamingRule', 'preserve');
step03JaccardTable = readtable(step03JaccardSummaryFile, ...
    'FileType', 'text', 'Delimiter', '\t', ...
    'VariableNamingRule', 'preserve');
step03TopCandidateTable = readtable(step03TopCandidateFile, ...
    'FileType', 'text', 'Delimiter', '\t', ...
    'VariableNamingRule', 'preserve');

step02Summary = jsondecode(fileread(step02SummaryFile));
step03Summary = jsondecode(fileread(step03SummaryFile));
step02Mat = load(step02MatFile, ...
    'modelSummaryTable', 'featureSelectionFrequency', 'summary');
step03Mat = load(step03MatFile, ...
    'rankByCandidate', 'finalRank', 'holdoutGlobalRow', 'summary');

localAssertTableColumns(step02FigureTable, { ...
    'PSOIteration', 'MedianBestFitness', 'BestFitnessQ1', ...
    'BestFitnessQ3', 'MedianSelectedDescriptorCount', ...
    'SelectedDescriptorCountQ1', 'SelectedDescriptorCountQ3'}, ...
    'Step 02 figure-source data');

localAssertTableColumns(step02Mat.modelSummaryTable, { ...
    'Seed', 'SelectedFeatureCount', 'BestFitness', ...
    'RelativeGap', 'P'}, 'Step 02 model-summary table');

localAssertTableColumns(step03JaccardTable, { ...
    'TopK', 'ModelPairCount', 'JaccardQ1', ...
    'MedianJaccard', 'JaccardQ3'}, ...
    'Step 03 Jaccard@K summary data');

localAssertTableColumns(step03TopCandidateTable, { ...
    'Rank', 'MeanRankAcrossSeeds', 'RankP10AcrossSeeds', ...
    'RankP90AcrossSeeds', 'BestRankAcrossSeeds', ...
    'WorstRankAcrossSeeds'}, ...
    'Step 03 top-candidate uncertainty data');

step02FigureTable = sortrows(step02FigureTable, 'PSOIteration');
step03JaccardTable = sortrows(step03JaccardTable, 'TopK');
step03TopCandidateTable = sortrows(step03TopCandidateTable, 'Rank');

assert(isfield(step02Summary, 'ModelCount') ...
    && isfield(step02Summary, 'GenerationCount') ...
    && isfield(step02Summary, 'ObjectiveDefinition') ...
    && isfield(step02Summary, 'DistanceEpsilon'), ...
    'Step 02 summary JSON lacks required metadata.');
assert(isfield(step03Summary, 'ModelCount') ...
    && isfield(step03Summary, 'RankingMethod') ...
    && isfield(step03Summary, 'ObjectiveDefinition') ...
    && isfield(step03Summary, 'DistanceEpsilon'), ...
    'Step 03 summary JSON lacks required metadata.');

modelCount = double(step02Summary.ModelCount);
generationCount = double(step02Summary.GenerationCount);
expectedObjective = '-((D2-D1)/(D1+epsilon))*F*P';

normalizationSummaries = {step02Summary, step03Summary, ...
    step02Mat.summary, step03Mat.summary};
for summaryIndex = 1:numel(normalizationSummaries)
    currentSummary = normalizationSummaries{summaryIndex};
    assert(isfield(currentSummary, 'PAggregation') ...
        && strcmp(currentSummary.PAggregation, 'mean_non_medoid'), ...
        ['Mixed P definitions are not allowed. Supply compatible mean-P models ' ...
         'and rerun step03_rank_candidates before plotting.']);
end

assert(modelCount == double(step03Summary.ModelCount), ...
    'Step 02 and Step 03 model counts disagree; do not mix analyses.');
assert(strcmp(step02Summary.ObjectiveDefinition, expectedObjective) ...
    && strcmp(step03Summary.ObjectiveDefinition, expectedObjective), ...
    'Step 02 or Step 03 does not use the current relative-gap objective.');
assert(isequal(double(step02Summary.DistanceEpsilon), ...
    double(step03Summary.DistanceEpsilon)), ...
    'Step 02 and Step 03 DistanceEpsilon values disagree.');
assert(double(step02Mat.summary.ModelCount) == modelCount ...
    && double(step03Mat.summary.ModelCount) == modelCount, ...
    'MAT ModelCount disagrees with JSON summary.');

assert(height(step02FigureTable) == generationCount, ...
    'Step 02 figure-source row count disagrees with GenerationCount.');
assert(isequal(double(step02FigureTable.PSOIteration), ...
    (1:generationCount).'), ...
    'PSOIteration must equal 1:GenerationCount.');
assert(all(step02FigureTable.BestFitnessQ1 ...
    <= step02FigureTable.MedianBestFitness) ...
    && all(step02FigureTable.MedianBestFitness ...
    <= step02FigureTable.BestFitnessQ3), ...
    'Fitness Q1/median/Q3 values are not ordered.');
assert(all(step02FigureTable.SelectedDescriptorCountQ1 ...
    <= step02FigureTable.MedianSelectedDescriptorCount) ...
    && all(step02FigureTable.MedianSelectedDescriptorCount ...
    <= step02FigureTable.SelectedDescriptorCountQ3), ...
    'Descriptor-count Q1/median/Q3 values are not ordered.');

modelSummaryTable = step02Mat.modelSummaryTable;
featureSelectionFrequency = double(step02Mat.featureSelectionFrequency(:));
assert(height(modelSummaryTable) == modelCount, ...
    'Step 02 model-summary row count differs from ModelCount.');
assert(all(isfinite(featureSelectionFrequency)) ...
    && all(featureSelectionFrequency >= 0) ...
    && all(featureSelectionFrequency <= 1), ...
    'Descriptor selection frequencies must be finite and in [0,1].');

expectedPairCount = modelCount * (modelCount - 1) / 2;
assert(all(double(step03JaccardTable.ModelPairCount) == expectedPairCount), ...
    'Jaccard@K pair count differs from nchoosek(ModelCount,2).');
assert(all(step03JaccardTable.JaccardQ1 >= 0) ...
    && all(step03JaccardTable.JaccardQ3 <= 1) ...
    && all(step03JaccardTable.JaccardQ1 ...
    <= step03JaccardTable.MedianJaccard) ...
    && all(step03JaccardTable.MedianJaccard ...
    <= step03JaccardTable.JaccardQ3), ...
    'Jaccard quantile bounds are invalid.');

candidateFigureCount = height(step03TopCandidateTable);
assert(candidateFigureCount >= 1, 'At least one top candidate is required for uncertainty plotting.');
assert(isequal(double(step03TopCandidateTable.Rank), ...
    (1:candidateFigureCount).'), ...
    'Top-candidate Rank must equal 1:N.');
assert(all(step03TopCandidateTable.BestRankAcrossSeeds ...
    <= step03TopCandidateTable.RankP10AcrossSeeds) ...
    && all(step03TopCandidateTable.RankP10AcrossSeeds ...
    <= step03TopCandidateTable.RankP90AcrossSeeds) ...
    && all(step03TopCandidateTable.RankP90AcrossSeeds ...
    <= step03TopCandidateTable.WorstRankAcrossSeeds), ...
    'Top-candidate best/P10/P90/worst ranks are not ordered.');

rankByCandidate = step03Mat.rankByCandidate;
finalRank = double(step03Mat.finalRank(:));
holdoutGlobalRow = double(step03Mat.holdoutGlobalRow(:));
formalCandidateCount = size(rankByCandidate, 1);
assert(size(rankByCandidate, 2) == modelCount, ...
    'rankByCandidate column count differs from ModelCount.');
assert(numel(finalRank) == formalCandidateCount ...
    && numel(holdoutGlobalRow) == formalCandidateCount, ...
    'finalRank or holdoutGlobalRow length differs from holdout count.');
assert(isequal(sort(finalRank), (1:formalCandidateCount).'), ...
    'Step 03 finalRank is not a complete permutation of 1:N.');

finalF = double(modelSummaryTable.SelectedFeatureCount(:));
finalRelativeGap = double(modelSummaryTable.RelativeGap(:));
finalAbsFitness = abs(double(modelSummaryTable.BestFitness(:)));
finalP = double(modelSummaryTable.P(:));
assert(all(isfinite(finalP)) && all(finalP >= 0 & finalP <= 100), ...
    'Mean non-medoid P must be finite and lie in [0,100].');

assert(all(isfinite(finalF)) && all(finalF > 0) ...
    && all(isfinite(finalRelativeGap)) && all(finalRelativeGap > 0) ...
    && all(isfinite(finalAbsFitness)) && all(finalAbsFitness > 0), ...
    'Final model F, R, or absolute fitness is invalid.');

rhoFvsR = localSpearmanAverageTies(finalF, finalRelativeGap);
rhoFvsAbsJ = localSpearmanAverageTies(finalF, finalAbsFitness);
rhoRvsAbsJ = localSpearmanAverageTies(finalRelativeGap, finalAbsFitness);

correlationTable = table( ...
    ["Selected descriptors"; "Selected descriptors"; "Relative gap"], ...
    ["Relative gap"; "Absolute fitness"; "Absolute fitness"], ...
    [rhoFvsR; rhoFvsAbsJ; rhoRvsAbsJ], ...
    repmat(modelCount, 3, 1), ...
    'VariableNames', {'VariableX', 'VariableY', 'SpearmanRho', 'N'});
correlationFile = fullfile(resultDir, ...
    'model_diagnostic_correlations.tsv');
writetable(correlationTable, correlationFile, ...
    'FileType', 'text', 'Delimiter', '\t');

ensembleSubsetSizes = unique(double(ensembleSubsetSizesRequested(:).'));
maximumIndependentSize = floor(modelCount / 2);
ensembleSubsetSizes = ensembleSubsetSizes( ...
    ensembleSubsetSizes >= 1 & ensembleSubsetSizes <= maximumIndependentSize);
assert(~isempty(ensembleSubsetSizes), ...
    'No valid independent M-vs-M sizes; require 2*M<=ModelCount.');
ensembleSubsetSizes = sort(ensembleSubsetSizes, 'ascend');
ensembleSizeCount = numel(ensembleSubsetSizes);

actualEnsembleTopK = min(double(ensembleTopK), formalCandidateCount);

independentSpearman = nan(ensembleStabilityRepeats, ensembleSizeCount);
independentTopKJaccard = nan(ensembleStabilityRepeats, ensembleSizeCount);

% Resample disjoint model groups without modifying models or the formal ranking.
originalRngState = rng;
rngCleanup = onCleanup(@() rng(originalRngState));
rng(ensembleStabilityRandomSeed, 'twister');

fprintf('\nComputing independent M-vs-M ensemble stability:');
for sizeIndex = 1:ensembleSizeCount
    currentSize = ensembleSubsetSizes(sizeIndex);
    fprintf(' M=%d', currentSize);

    for repeatIndex = 1:ensembleStabilityRepeats

        selectedModels = randperm(modelCount, 2 * currentSize);
        modelsA = selectedModels(1:currentSize);
        modelsB = selectedModels(currentSize + 1:2 * currentSize);

        meanRankA = mean(double(rankByCandidate(:, modelsA)), 2);
        [~, orderA] = sortrows([meanRankA, holdoutGlobalRow], [1, 2]);
        rankA = zeros(formalCandidateCount, 1);
        rankA(orderA) = (1:formalCandidateCount).';

        meanRankB = mean(double(rankByCandidate(:, modelsB)), 2);
        [~, orderB] = sortrows([meanRankB, holdoutGlobalRow], [1, 2]);
        rankB = zeros(formalCandidateCount, 1);
        rankB(orderB) = (1:formalCandidateCount).';

        independentSpearman(repeatIndex, sizeIndex) = corr(rankA, rankB);

        topMaskA = false(formalCandidateCount, 1);
        topMaskB = false(formalCandidateCount, 1);
        topMaskA(orderA(1:actualEnsembleTopK)) = true;
        topMaskB(orderB(1:actualEnsembleTopK)) = true;
        independentTopKJaccard(repeatIndex, sizeIndex) = ...
            sum(topMaskA & topMaskB) ./ sum(topMaskA | topMaskB);
    end
end
fprintf(' complete.\n');
clear rngCleanup

ensembleSpearmanMedian = median(independentSpearman, 1).';
ensembleSpearmanQ1 = column_percentile(independentSpearman, 25).';
ensembleSpearmanQ3 = column_percentile(independentSpearman, 75).';
ensembleTopKMedian = median(independentTopKJaccard, 1).';
ensembleTopKQ1 = column_percentile(independentTopKJaccard, 25).';
ensembleTopKQ3 = column_percentile(independentTopKJaccard, 75).';

ensembleLongTable = table();
for sizeIndex = 1:ensembleSizeCount
    currentBlock = table( ...
        repmat(ensembleSubsetSizes(sizeIndex), ensembleStabilityRepeats, 1), ...
        (1:ensembleStabilityRepeats).', ...
        independentSpearman(:, sizeIndex), ...
        independentTopKJaccard(:, sizeIndex), ...
        'VariableNames', {'EnsembleSize', 'Repeat', ...
        'IndependentEnsembleSpearman', 'IndependentTopKJaccard'});
    ensembleLongTable = [ensembleLongTable; currentBlock];
end
ensembleLongFile = fullfile(resultDir, ...
    'independent_ensemble_stability.tsv');
writetable(ensembleLongTable, ensembleLongFile, ...
    'FileType', 'text', 'Delimiter', '\t');

ensembleSummaryTable = table(ensembleSubsetSizes(:), ...
    ensembleSpearmanQ1, ensembleSpearmanMedian, ensembleSpearmanQ3, ...
    ensembleTopKQ1, ensembleTopKMedian, ensembleTopKQ3, ...
    'VariableNames', {'EnsembleSize', ...
    'SpearmanQ1', 'MedianSpearman', 'SpearmanQ3', ...
    'TopKJaccardQ1', 'MedianTopKJaccard', 'TopKJaccardQ3'});
ensembleSummaryFile = fullfile(resultDir, ...
    'independent_ensemble_stability_summary.tsv');
writetable(ensembleSummaryTable, ensembleSummaryFile, ...
    'FileType', 'text', 'Delimiter', '\t');

fig3aBase = fullfile(figureDir, 'FIG3A');
fig3bBase = fullfile(figureDir, 'FIG3B');
fig3cBase = fullfile(figureDir, 'FIG3C');
fig4aBase = fullfile(figureDir, 'FIG4A');
fig4bBase = fullfile(figureDir, 'FIG4B');
fig4dBase = fullfile(figureDir, 'FIG4D');
fig4eBase = fullfile(figureDir, 'FIG4E');
fig4cBase = fullfile(figureDir, 'FIG4C');

allFigureBases = {fig3aBase, fig3bBase, fig3cBase, fig4aBase, ...
    fig4bBase, fig4dBase, fig4eBase, fig4cBase};
for baseIndex = 1:numel(allFigureBases)
    localPrepareFigureOutput(allFigureBases{baseIndex}, overwriteExistingFigures);
end

visibilityOptions = {'off', 'on'};
figureVisibility = visibilityOptions{1 + double(showFiguresOnScreen)};

blue = [0, 114, 178] ./ 255;
lightBlue = [86, 180, 233] ./ 255;
vermillion = [213, 94, 0] ./ 255;
lightOrange = [0.96, 0.82, 0.64];
lightGray = [0.72, 0.72, 0.72];
darkGray = [0.30, 0.30, 0.30];

generation = double(step02FigureTable.PSOIteration);
fitnessMedian = double(step02FigureTable.MedianBestFitness);
fitnessQ1 = double(step02FigureTable.BestFitnessQ1);
fitnessQ3 = double(step02FigureTable.BestFitnessQ3);
descriptorMedian = double(step02FigureTable.MedianSelectedDescriptorCount);
descriptorQ1 = double(step02FigureTable.SelectedDescriptorCountQ1);
descriptorQ3 = double(step02FigureTable.SelectedDescriptorCountQ3);

topK = double(step03JaccardTable.TopK);
jaccardMedian = double(step03JaccardTable.MedianJaccard);
jaccardQ1 = double(step03JaccardTable.JaccardQ1);
jaccardQ3 = double(step03JaccardTable.JaccardQ3);

fig3a = figure('Visible', figureVisibility, 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2, 2, regularFigureSizeCm(1), regularFigureSizeCm(2)]);
ax = axes(fig3a);
hold(ax, 'on');
fill(ax, [generation; flipud(generation)], ...
    [fitnessQ1; flipud(fitnessQ3)] ./ fitnessDisplayScale, ...
    lightBlue, 'EdgeColor', 'none', 'FaceAlpha', 0.32, 'HandleVisibility', 'off');
plot(ax, generation, fitnessMedian ./ fitnessDisplayScale, ...
    'Color', blue, 'LineWidth', 1.55, 'HandleVisibility', 'off');
xlabel(ax, 'PSO generation');
ylabel(ax, 'Best-so-far objective (\times10^6)');
localStyleAxes(ax, figureFontName, baseFontSizePt);
ax.YAxis.Exponent = 0;
xlim(ax, [1, generationCount]);
hold(ax, 'off');
drawnow;
export_publication_figure(fig3a, fig3aBase, figureResolutionDpi);

fig3b = figure('Visible', figureVisibility, 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2, 2, regularFigureSizeCm(1), regularFigureSizeCm(2)]);
ax = axes(fig3b);
hold(ax, 'on');
fill(ax, [generation; flipud(generation)], ...
    [descriptorQ1; flipud(descriptorQ3)], ...
    lightOrange, 'EdgeColor', 'none', 'FaceAlpha', 0.50, 'HandleVisibility', 'off');
plot(ax, generation, descriptorMedian, ...
    'Color', vermillion, 'LineWidth', 1.55, 'HandleVisibility', 'off');
xlabel(ax, 'PSO generation');
ylabel(ax, 'Number of selected descriptors');
localStyleAxes(ax, figureFontName, baseFontSizePt);
xlim(ax, [1, generationCount]);
ylim(ax, localRoundedDataRange([descriptorQ1; descriptorQ3], 100));
hold(ax, 'off');
drawnow;
export_publication_figure(fig3b, fig3bBase, figureResolutionDpi);

fig3c = figure('Visible', figureVisibility, 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2, 2, regularFigureSizeCm(1), regularFigureSizeCm(2)]);
ax = axes(fig3c);
hold(ax, 'on');
scatter(ax, finalF, finalRelativeGap, 26, blue, 'filled', ...
    'MarkerFaceAlpha', 0.78, 'MarkerEdgeColor', 'w', 'LineWidth', 0.45);
xlabel(ax, 'Number of selected descriptors (F)');
ylabel(ax, 'Relative separation (R)');
localStyleAxes(ax, figureFontName, baseFontSizePt);
set(ax, 'XGrid', 'off', 'YGrid', 'off');
text(ax, 0.97, 0.96, sprintf('\\rho = %s%.3f\nn = %d', char(8722), abs(rhoFvsR), modelCount), ...
    'Units', 'normalized', 'HorizontalAlignment', 'right', ...
    'VerticalAlignment', 'top', 'FontName', figureFontName, ...
    'FontSize', baseFontSizePt, 'Color', darkGray, 'Interpreter', 'tex');
hold(ax, 'off');
drawnow;
export_publication_figure(fig3c, fig3cBase, figureResolutionDpi);

fig4a = figure('Visible', figureVisibility, 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2, 2, regularFigureSizeCm(1), regularFigureSizeCm(2)]);
ax = axes(fig4a);
hold(ax, 'on');
sortedFeatureFrequency = sort(featureSelectionFrequency, 'descend');
frequencyOrder = (1:numel(sortedFeatureFrequency)).';
plot(ax, frequencyOrder, sortedFeatureFrequency, ...
    'Color', darkGray, 'LineWidth', 1.25);
xlabel(ax, 'Descriptor frequency rank');
ylabel(ax, 'Selection frequency');
localStyleAxes(ax, figureFontName, baseFontSizePt);
set(ax, 'YLim', [0, 1], 'YGrid', 'off');
xlim(ax, [1, numel(sortedFeatureFrequency)]);
hold(ax, 'off');
drawnow;
export_publication_figure(fig4a, fig4aBase, figureResolutionDpi);

fig4b = figure('Visible', figureVisibility, 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2, 2, regularFigureSizeCm(1), regularFigureSizeCm(2)]);
ax = axes(fig4b);
hold(ax, 'on');
fill(ax, [topK; flipud(topK)], [jaccardQ1; flipud(jaccardQ3)], ...
    lightBlue, 'EdgeColor', 'none', 'FaceAlpha', 0.28, 'HandleVisibility', 'off');
plot(ax, topK, jaccardMedian, '-o', ...
    'Color', blue, 'MarkerFaceColor', blue, 'MarkerEdgeColor', 'w', ...
    'MarkerSize', 4.2, 'LineWidth', 1.35);
set(ax, 'XScale', 'log', 'YLim', [0, 1]);
if isscalar(topK)
    xlim(ax, [0.8 .* topK, 1.25 .* topK]);
else
    xlim(ax, [min(topK) ./ 1.15, max(topK) .* 1.15]);
end
xticks(ax, topK);
xticklabels(ax, localCompactIntegerLabels(topK));
xlabel(ax, 'Top-K threshold');
ylabel(ax, 'Pairwise Jaccard index');
localStyleAxes(ax, figureFontName, baseFontSizePt);
