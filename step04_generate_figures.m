    'Units', 'centimeters', 'Position', [2, 2, tallFigureSizeCm(1), tallFigureSizeCm(2)]);
ax = axes(fig4c);
hold(ax, 'on');
candidateY = (1:candidateFigureCount).';

rangeLegend = plot(ax, nan, nan, '-', 'Color', lightGray, 'LineWidth', 0.9);
